"""
Scheduling-accuracy test signals (Task 3 spike, Docs/Captures/README.md "Scheduling spike").

    python FMOD/Tools/spike_click.py
    fmodstudiocl.exe -script FMOD/Tools/spike_click.js FMOD/ChordPulse/ChordPulse.fspro
    python FMOD/Tools/instruments.py   (registers the SpikeClick instrument through LAYERS)
    fmodstudiocl.exe -script FMOD/Tools/instruments.js FMOD/ChordPulse/ChordPulse.fspro
    fmodstudiocl.exe -build FMOD/ChordPulse/ChordPulse.fspro      (separate command)

Writes:
- FMOD/ChordPulse/Assets/Spike/click_1k.wav, click_3k.wav: 5 ms sine bursts (1 kHz / 3 kHz), same envelope,
  48 kHz mono 16-bit. The attack is at sample 0 (onset 0 s).
- spike_click.js: adds a "Spike ref" group track to event:/Music/ChordPulseGame with a 1 kHz click on every beat of
  all 32 bars (4 sections x 8 bars). Every click has a parameter condition SpikeRef in [0.5, 1], so the track is
  silent unless Unity sets the event-local parameter SpikeRef = 1. Idempotent (removes its old track first).
- register(lib): the SpikeClick instrument (3 kHz click) for instruments.py -> event:/Inst/SpikeClick.
"""
import json
import math
import os
import struct
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "ChordPulse", "Assets")
REL_1K = "Spike/click_1k.wav"
REL_3K = "Spike/click_3k.wav"

RATE = 48000
LENGTH_S = 0.005
AMPLITUDE = 0.7
ATTACK_S = 0.0002     # raised-cosine fade-in, short enough to keep the onset sharp
RELEASE_S = 0.001     # raised-cosine fade-out at the end of the 5 ms burst

# Same tempo map as the other generators: 4 sections x 8 bars x 4 beats.
SECTIONS = []
_t = 0.0
for _bpm in (108, 116, 124, 132):
    SECTIONS.append((_t, _bpm))
    _t += 32 * 60.0 / _bpm
BEATS_PER_SECTION = 32


def click_samples(freq):
    n = int(round(LENGTH_S * RATE))
    a, r = int(ATTACK_S * RATE), int(RELEASE_S * RATE)
    out = []
    for i in range(n):
        env = 1.0
        if i < a:
            env = 0.5 - 0.5 * math.cos(math.pi * i / a)
        elif i >= n - r:
            env = 0.5 - 0.5 * math.cos(math.pi * (n - 1 - i) / r)
        out.append(AMPLITUDE * env * math.sin(2 * math.pi * freq * i / RATE))
    return out


def short_term_rms_db(samples, window_s=0.05):
    """Peak short-term RMS over a 50 ms window (the burst is shorter, so this is the whole burst over 50 ms)."""
    n = int(window_s * RATE)
    energy = sum(s * s for s in samples)
    return 10 * math.log10(energy / n)


def write_wav(rel, samples):
    path = os.path.join(ASSETS, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(b"".join(struct.pack("<h", int(round(max(-1, min(1, s)) * 32767))) for s in samples))
    return path


CLICK_3K_RMS_DB = round(short_term_rms_db(click_samples(3000)), 1)


def register(lib):
    """instruments.py layer: one note (MIDI 72) of the 3 kHz click; onset 0."""
    lib.add("SpikeClick", [(REL_3K, 72, CLICK_3K_RMS_DB, 0.0)], 8)
    lib.need("SpikeClick", 72)


def beat_times():
    times = []
    for start, bpm in SECTIONS:
        for b in range(BEATS_PER_SECTION):
            times.append(round(start + b * 60.0 / bpm, 6))
    return times


JS_TEMPLATE = r"""// Generated by FMOD/Tools/spike_click.py - edit the Python file, not this one.
var TIMES = __TIMES__;
var FILE = "__FILE__";
var TRACK = "Spike ref";

function log(m) { console.log("[spike] " + m); }
var project = studio.project;
var ev = project.lookup("event:/Music/ChordPulseGame");
if (!ev) throw "event:/Music/ChordPulseGame not found";
var assetsRoot = project.filePath.replace(/[^\/\\]+$/, "") + "Assets/";

// --- SpikeRef: event-local (not global) 0..1; 0 = track silent ---
// Continuous (User), not UserDiscrete: a discrete preset with max 1 is saved without "maximum" and loads as max 0.
var preset = project.lookup("parameter:/SpikeRef");
if (!preset) {
    project.workspace.addGameParameter({ name: "SpikeRef", type: project.parameterType.User, min: 0, max: 1 });
    preset = project.lookup("parameter:/SpikeRef");
    log("created parameter SpikeRef");
}
preset.parameter.parameterType = project.parameterType.User;
preset.parameter.minimum = 0; preset.parameter.maximum = 1; preset.parameter.initialValue = 0;
var has = false;
ev.parameters.forEach(function (x) { if (x.preset && (x.preset.id === preset.parameter.id || x.preset.id === preset.id)) has = true; });
if (!has) { ev.addGameParameter(preset); log("added SpikeRef to event"); }

// --- undo an earlier run ---
var old = [];
ev.groupTracks.forEach(function (t) { if (t.mixerGroup.name === TRACK) old.push(t); });
old.forEach(function (t) { project.deleteObject(t); });
if (old.length) log("removed old " + TRACK);

var af = null;
project.model.AudioFile.findInstances().forEach(function (a) {
    if (a.isValid && a.masterAssetFolder && a.length > 0 && a.assetPath === FILE) af = a;
});
if (!af) { af = project.importAudioFile(assetsRoot + FILE); log("imported " + FILE); }
if (!af) throw "could not import " + FILE;

// Straight to the event master, outside Music Bed / Harmony, so mix parameters do not touch it.
var t = project.create("GroupTrack");
t.mixerGroup.name = TRACK;
t.mixerGroup.output = ev.mixer.masterBus;
ev.relationships.groupTracks.add(t);
TIMES.forEach(function (start) {
    var s = t.addSound(ev.timeline, "SingleSound", start, 0.05);
    s.audioFile = af;
    s.addParameterCondition(preset, 0.5, 1.0);
});
log("placed " + TIMES.length + " clicks");
project.save();
log("saved");
"""


def main():
    write_wav(REL_1K, click_samples(1000))
    write_wav(REL_3K, click_samples(3000))
    times = beat_times()
    js = JS_TEMPLATE.replace("__TIMES__", json.dumps(times)).replace("__FILE__", REL_1K)
    with open(os.path.join(HERE, "spike_click.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(js)
    print("clicks", len(times), "-> spike_click.js; click_3k short-term RMS", CLICK_3K_RMS_DB, "dB")


if __name__ == "__main__":
    main()
