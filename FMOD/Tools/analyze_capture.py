"""Analyse WAV recordings made by Unity's AudioCapture / CaptureScenario (Docs/Captures/README.md).

  python FMOD/Tools/analyze_capture.py rms <wav> --window-beats 4 --bpm-map seed7 [--compare <wav2>]
      Per-window RMS (dBFS). Windows are N beats long, cut along the beat log the capture wrote next to the WAV
      (<wav minus .wav>.beats.csv: beat,frame,bpm). --bpm-map is that log: a path to a csv, or any label such as
      "seed7" meaning "use the sidecar log of the WAV". With --compare the second recording is cut the same way
      (by its own beat log) and the per-window difference is printed (max abs difference at the end).

  python FMOD/Tools/analyze_capture.py onsets <wav> --ref-band 900-1100 --test-band 2800-3200
      Finds attack times in two frequency bands and pairs them: ref (e.g. a metronome click) vs test (e.g. a kill
      chord click). Prints the mean / max absolute and mean signed difference in ms.

  python FMOD/Tools/analyze_capture.py spike <wav> [--allow-missing N] [--stall-beats 9.8,15.7] [--xcorr [--xcorr-window-ms W]] [--verbose]
      Clock mode (the .beats.csv has a dsp column and there is no .timeline.csv: takes from unity-music-clock Task 6
      on): the reference is the beat's frame in .beats.csv, computed by the music clock. For every click of .spike.csv
      the error is attack frame - beat frame (ms; the test-band onset nearest the beat within half a beat). Prints mean
      |error| / max / mean signed, for all clicks, per lead, for the 4 beats after each tempo change and (with
      --stall-beats) for the 4 beats after each forced stall; missing (no click), late (> +5 ms), early (< -5 ms).
      The onset detector's own bias on the SpikeClick is measured on every run (the click generated by spike_click.py,
      placed at 16 known samples in silence, found by the same band_onsets) and printed. Every figure is printed raw
      and corrected (raw - bias); the gate is judged on the corrected values: exit 1 unless mean <= 2 ms, max <= 5 ms
      (after changes and stalls too), early 0, late 0 (+-5 ms), missing <= N. Also prints the corrected mean signed
      error against the +-0.5 ms calibration trigger. --xcorr: the exact lag of every click in samples, by cross-
      correlation with the click waveform (both band-passed 2-4 kHz) within +-10 ms of its beat frame (+-W ms with
      --xcorr-window-ms; with CaptureScenario.spikeTarget on another bus this gives that bus's onset against the clock).

  python FMOD/Tools/analyze_capture.py spike <wav> [--offset-ms X]
      Timeline mode (older takes with a .timeline.csv): Task 3 scheduling spike. Pairs every scheduled SpikeClick (3 kHz, test band 2800-3200) with the Spike ref
      timeline click (1 kHz, ref band 900-1100) of the same beat, using the take's sidecar logs
      (.beats.csv, .spike.csv, .timeline.csv). Prints error stats before and after removing a constant offset
      (the mean signed error of the take, or --offset-ms), for all beats and for the 4 beats after each section
      change (timeline discontinuity or tempo change). The verdict covers the measured (paired) beats only; beats
      that were not scheduled or have no click are counted and listed separately, never folded into the stats:
      "GATE: PASS on N measured beats; M not scheduled, K no click" (or FAIL). A PASS with M > 0 is conditional.

  python FMOD/Tools/analyze_capture.py frames <wav>
      Reads <wav minus .wav>.frames.csv (dt,beat,bpm per Unity frame: the visual beat SoundManager.BeatPosition).
      Prints the number of backward steps, max |delta beat - dt*bpm/60| (with its beat position) and the longest hold:
      consecutive frames whose delta beat is below 0.25 * dt*bpm/60, in ms of wall time, with its beat position. Exit 1
      if the beat ever goes back, a frame deviates by more than 0.05 beat, or the longest hold exceeds 30 ms.
      Frames marked forced=1 (CaptureScenario stallMs: the frame that carries a forced Thread.Sleep) are printed on
      their own and left out of the deviation and hold checks.

  python FMOD/Tools/analyze_capture.py landings <wav> [--at-beats 30.5,47.7]
      For every 16th beat of the beat log: delay of the logged boundary frame against the frame predicted from the
      previous beat and its BPM (ms), RMS of the first and the next half beat after the predicted boundary, RMS of the
      same place one phrase (boundary b-8) earlier, and silent runs (>= 20 ms, 5 ms windows with peak below -70 dBFS)
      within one beat after the predicted boundary. A run is printed as a "rest" (separately from the gaps) only if the
      window at the same offset in beats (ms scaled by bpm[b] / bpm[b-4]) after the previous bar's downbeat (beat b-4,
      its logged frame) is entirely silent by the same rule; a run starting less than 20 ms after the boundary, or any run when beat b-4 is not in the
      beat log, is always a gap.
      --at-beats: the same silent-run check within one beat after each given (fractional) beat, e.g. forced stalls; a
      run is a rest only if the same window 4 beats earlier is entirely silent. Prints the number of gaps.

  python FMOD/Tools/analyze_capture.py bands <wav> [--compare <ref wav>] [--window-beats 4] [--from-beat 8]
        [--hit-every N --hit-from M] [--chord-every 4 --chord-offset 1 --chord-ms 80]
        [--period 4 --region 2.5-4.0 ...]
      Band-limited RMS (dBFS) in <300 Hz, 300-2000 Hz and >2000 Hz (4th-order Butterworth, zero phase, mono mean), per
      window of --window-beats beats cut along each take's own beat log. With --compare the reference take is cut the
      same way and the per-band difference (take - reference) is printed, plus the median over the windows from
      --from-beat on (a Danger take needs ~0.5 s for its low-pass to arrive). --hit-every N: for every beat that is a
      multiple of N (from --hit-from, default N) the --hit-step-ms (100) windows from the beat, --hit-steps (8) of them, per band, take vs
      reference (Hurt dip and recovery). --chord-every K --chord-ms L: the first L ms after every K-th beat (the kill
      chord attacks of the baseline scenario), take vs reference.

  python FMOD/Tools/analyze_capture.py duck <duck wav> --compare <duck nokills wav> [--chord-every 4 --chord-offset 1]
      Kill-chord ducking of the Harmony bus (Task 6/7 method): the gain that maps the no-kill take onto the duck take,
      least squares per 20 ms bin (bins with the no-kill RMS below -60 dBFS skipped) over the 375 ms after every chord beat (beat k*4+1: the baseline scenario queues the
      kill on beat k*4 for the next beat), each no-kill segment aligned to the duck segment by cross-correlation
      (+-20 ms). Prints the median over chords of the per-chord mean gain (dB), the mean over all bins and the median
      of the per-chord minimum.

  python FMOD/Tools/analyze_capture.py ladderfade <take> --break-beat B [--reference <no-break take>] [--rung0 <rung-0 take>]
        [--edge-beat E]
  python FMOD/Tools/analyze_capture.py ladderfade --selftest
      Combo-ladder break fade (CaptureScenario combobreak). Half-beat windows, all buses together, cut along each take's
      own beat log: 2 beats before the break, the 2-beat fade, 2 beats after it. Per window the take's RMS and, with
      --reference, the reference's and the difference. In a full mix the floor layers keep playing, so the level of the
      layers above the floor is only visible against other takes: the takes are deterministic for a seed, so the take
      is first checked against the reference sample for sample before the break (null depth, 4-beat window diffs); with
      --rung0 too, the above-floor signal is take - rung0 and ref - rung0 (floor layers cancel) and their ratio is the
      fade gain, printed per window next to the 1 - t^2 curve (window mean as RMS), and per 1/8 beat. Also: the
      monotonic check of the 4 fade windows against the reference, the 2 beats after the fade against the rung-0 take
      (+-1 dB), clicks (1 ms windows more than 12 dB above both neighbours, raw and on the first difference) in the fade
      and in the half beat after it, the ladder log (<take>.ladder.csv: fade start, the frame the rung reached the floor,
      fever / guest rows), the above-floor signal in 2 ms windows around the rung drop (end-of-fade stop) and, with
      --edge-beat, the 20 ms RMS before / after a bar line inside the fade. --selftest: a 1 kHz sine under 1 - t^2,
      written as a take and read back; the four fade windows must match the curve within 0.5 dB.

  python FMOD/Tools/analyze_capture.py kicks <take> --reference <take> [--from 36 --to 46 --ms 30]
      RMS of the first 30 ms after every even beat (kick), take vs reference.

Needs numpy and scipy. Note: numpy lives in the user site-packages here, so `python -I` (isolated mode) cannot import
it; run with plain `python` (the WAVs are our own captures, nothing untrusted is loaded).
"""
import argparse
import csv
import os
import sys

import numpy as np


def read_wav(path):
    """Minimal RIFF reader for 32-bit float / 16-bit PCM; returns (float32 array [n, ch], rate)."""
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"RIFF" or data[8:12] != b"WAVE":
        raise SystemExit("not a WAV file: " + path)
    pos, fmt, samples = 12, None, None
    while pos + 8 <= len(data):
        chunk_id = data[pos:pos + 4]
        size = int.from_bytes(data[pos + 4:pos + 8], "little")
        body = data[pos + 8:pos + 8 + size]
        if chunk_id == b"fmt ":
            fmt = (int.from_bytes(body[0:2], "little"), int.from_bytes(body[2:4], "little"),
                   int.from_bytes(body[4:8], "little"), int.from_bytes(body[14:16], "little"))
        elif chunk_id == b"data":
            samples = body
        pos += 8 + size + (size & 1)
    if fmt is None or samples is None:
        raise SystemExit("missing fmt/data chunk: " + path)
    tag, channels, rate, bits = fmt
    if tag == 3 and bits == 32:
        audio = np.frombuffer(samples[:len(samples) // 4 * 4], dtype="<f4")
    elif tag == 1 and bits == 16:
        audio = np.frombuffer(samples[:len(samples) // 2 * 2], dtype="<i2").astype(np.float32) / 32768.0
    else:
        raise SystemExit("unsupported WAV format tag=%d bits=%d" % (tag, bits))
    audio = audio[:len(audio) // channels * channels].reshape(-1, channels)
    return audio.astype(np.float32), rate


def read_beats(wav_path, bpm_map):
    path = bpm_map if bpm_map and os.path.isfile(bpm_map) else os.path.splitext(wav_path)[0] + ".beats.csv"
    if not os.path.isfile(path):
        raise SystemExit("beat log not found: " + path)
    with open(path, newline="") as f:
        return [(int(r["beat"]), int(r["frame"]), int(round(float(r["bpm"])))) for r in csv.DictReader(f)]


def window_rms_db(wav_path, window_beats, bpm_map):
    audio, rate = read_wav(wav_path)
    beats = read_beats(wav_path, bpm_map)
    rows = []
    for first in range(0, len(beats) - window_beats, window_beats):
        a, b = beats[first], beats[first + window_beats]
        seg = audio[a[1]:b[1]]
        rms = float(np.sqrt(np.mean(seg.astype(np.float64) ** 2))) if len(seg) else 0.0
        db = 20 * np.log10(rms) if rms > 0 else float("-inf")
        # The beat log is stamped on the Unity main thread: a frame hitch lumps beats together. Flag such windows.
        expected = window_beats * 60.0 / a[2]
        actual = (b[1] - a[1]) / rate
        rows.append((a[0], a[2], a[1] / rate, db, abs(actual - expected) > 0.1 * expected))
    return rows, audio, rate


def cmd_rms(args):
    rows, audio, rate = window_rms_db(args.wav, args.window_beats, args.bpm_map)
    other = None
    if args.compare:
        other, _, _ = window_rms_db(args.compare, args.window_beats, None)
    print("%s  (%.2f s, %d Hz)" % (args.wav, len(audio) / rate, rate))
    header = "window  beat   bpm  start_s   RMS dBFS" + ("   other dBFS    diff dB" if other else "")
    print(header)
    worst = 0.0
    bad = 0
    for i, (beat, bpm, start, db, hitch) in enumerate(rows):
        line = "%5d  %4d  %4d  %7.2f  %9.2f%s" % (i, beat, bpm, start, db, "  ?" if hitch else "")
        bad += hitch
        if other and i < len(other):
            diff = other[i][3] - db
            worst = max(worst, abs(diff))
            line += "  %11.2f  %9.2f" % (other[i][3], diff)
        print(line)
    if bad:
        print("? = window length differs >10%% from the start BPM (tempo change inside the window, or a frame hitch: %d windows)" % bad)
    valid = [r[3] for r in rows if np.isfinite(r[3])]
    if valid:
        print("overall: mean %.2f dBFS, max %.2f dBFS, windows %d" % (np.mean(valid), np.max(valid), len(valid)))
    if other:
        print("max |diff| = %.3f dB over %d windows (limit 0.3 dB)" % (worst, min(len(rows), len(other))))
        return 0 if worst <= 0.3 else 1
    return 0


def parse_band(text):
    lo, hi = text.split("-")
    return float(lo), float(hi)


def band_onsets(mono, rate, band):
    from scipy import signal  # imported lazily: slow on a cold start, and rms does not need it
    sos = signal.butter(4, band, btype="bandpass", fs=rate, output="sos")
    env = np.abs(signal.sosfiltfilt(sos, mono))
    smooth = signal.butter(2, 300.0, btype="lowpass", fs=rate, output="sos")
    env = np.maximum(signal.sosfiltfilt(smooth, env), 0)
    peak = env.max()
    if peak <= 0:
        return np.array([])
    # Peaks at least 25% of the band maximum and 80 ms apart; the onset is where the envelope first rose
    # above 15% of that peak (so loud and quiet clicks are timed the same way).
    peaks, _ = signal.find_peaks(env, height=0.25 * peak, distance=int(0.08 * rate))
    onsets = []
    for p in peaks:
        lo = max(0, p - int(0.05 * rate))
        above = np.nonzero(env[lo:p + 1] >= 0.15 * env[p])[0]
        onsets.append((lo + (above[0] if len(above) else p - lo)) / rate)
    return np.array(onsets)


def cmd_onsets(args):
    audio, rate = read_wav(args.wav)
    mono = audio.mean(axis=1)
    ref = band_onsets(mono, rate, parse_band(args.ref_band))
    test = band_onsets(mono, rate, parse_band(args.test_band))
    if len(ref) == 0 or len(test) == 0:
        raise SystemExit("no onsets found (ref %d, test %d)" % (len(ref), len(test)))
    diffs = []
    for t in test:
        nearest = ref[np.argmin(np.abs(ref - t))]
        if abs(nearest - t) <= args.max_pair_ms / 1000.0:
            diffs.append((t - nearest) * 1000.0)
    print("ref onsets %d, test onsets %d, paired %d (within %.0f ms)" % (len(ref), len(test), len(diffs), args.max_pair_ms))
    if not diffs:
        return 1
    d = np.array(diffs)
    print("test - ref attack: mean |diff| %.2f ms, max |diff| %.2f ms, mean signed %.2f ms" %
          (np.mean(np.abs(d)), np.max(np.abs(d)), np.mean(d)))
    return 0


def read_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def stats(values):
    a = np.abs(np.array(values))
    return (float(a.mean()), float(a.max())) if len(a) else (float("nan"), float("nan"))


def cmd_spike(args):
    base = os.path.splitext(args.wav)[0]
    rows = read_csv(base + ".beats.csv")
    if rows and "dsp" in rows[0] and not os.path.isfile(base + ".timeline.csv"):
        return cmd_spike_clock(args)
    return cmd_spike_timeline(args)


def spike_click_waveform(rate):
    """The SpikeClick sample as generated by spike_click.py (3 kHz, 5 ms; attack at sample 0)."""
    import spike_click  # same folder; generator only, no side effects on import
    if rate != spike_click.RATE:
        raise SystemExit("spike click is generated at %d Hz, capture is %d Hz" % (spike_click.RATE, rate))
    return np.array(spike_click.click_samples(3000.0))


def detector_bias_samples(rate, count=16):
    """Bias of band_onsets on the SpikeClick itself: the click placed at known samples in silence (0.5 s apart, each
    with a different sub-period offset), onset found exactly as for a capture. Returns (mean, min, max) of found - true
    in samples (negative = the detector reports the click early)."""
    click = spike_click_waveform(rate)
    sig = np.zeros(int(rate * (1.0 + 0.5 * count)))
    pos = [int(rate * (0.5 + 0.5 * k)) + 7 * k for k in range(count)]
    for p in pos:
        sig[p:p + len(click)] += click
    found = band_onsets(sig, rate, (2800.0, 3200.0))
    if len(found) != count:
        raise SystemExit("detector bias: found %d of %d synthetic clicks" % (len(found), count))
    d = found * rate - np.array(pos)
    return float(d.mean()), float(d.min()), float(d.max())


def click_xcorr_lags(mono, rate, frames, window=480):
    """Exact click position by cross-correlation: the capture and the SpikeClick waveform, both band-passed 2-4 kHz
    (zero phase, so neither is shifted), correlated within +-window samples of each frame. Returns {frame: (lag,
    normalised peak)}; lag + = late."""
    from scipy import signal
    sos = signal.butter(4, (2000.0, 4000.0), btype="bandpass", fs=rate, output="sos")
    band = signal.sosfiltfilt(sos, mono.astype(np.float64))
    click = spike_click_waveform(rate)
    tmpl = signal.sosfiltfilt(sos, np.concatenate([np.zeros(500), click, np.zeros(500)]))[500:500 + len(click) + 200]
    out = {}
    for f in frames:
        if f - window < 0 or f + window + len(tmpl) > len(band):
            continue
        seg = band[f - window:f + window + len(tmpl)]
        c = np.correlate(seg, tmpl, mode="valid")
        k = int(np.argmax(c))
        peak = c[k] / (np.linalg.norm(tmpl) * np.linalg.norm(seg[k:k + len(tmpl)]) + 1e-30)
        out[f] = (k - window, float(peak))
    return out


def cmd_spike_clock(args):
    """Clock-referenced spike (unity-music-clock Task 7): every click against its beat's frame in .beats.csv, which the
    music clock computed (MusicTransport / BeatClock DSP sample -> AudioCapture.FrameAtDsp). No reference click.
    Raw errors come from band_onsets; the detector's own bias on the SpikeClick (detector_bias_samples) is measured on
    every run and subtracted for the corrected errors, on which the gate is judged."""
    audio, rate = read_wav(args.wav)
    base = os.path.splitext(args.wav)[0]
    beats = {int(r["beat"]): (int(r["frame"]), float(r["bpm"])) for r in read_csv(base + ".beats.csv")}
    spikes = read_csv(base + ".spike.csv")
    mono = audio.mean(axis=1)
    test = band_onsets(mono, rate, (2800.0, 3200.0))
    bias, bias_min, bias_max = detector_bias_samples(rate)
    bias_ms = bias / rate * 1000.0

    changes = [b for b in sorted(beats) if b - 1 in beats and beats[b][1] != beats[b - 1][1]]
    post = {}
    for c in changes:
        for b in range(c, c + 4):
            post[b] = c
    stalls = []
    if args.stall_beats:
        stalls = [float(v) for v in args.stall_beats.split(",") if v.strip()]
    after_stall = {}
    for s in stalls:
        first = int(np.floor(s)) + 1
        for b in range(first, first + 4):
            after_stall[b] = s

    wanted = sorted(int(r["beat"]) for r in spikes)
    not_scheduled = sorted(int(r["beat"]) for r in spikes if r["scheduled"] != "1")
    no_frame = [b for b in wanted if b not in beats]
    measured = [b for b in wanted if b in beats]
    # Every test-band onset belongs to the nearest wanted beat, if it lies within half a beat of it.
    assigned = {b: [] for b in measured}
    for t in test:
        frame_t = t * rate
        best, best_d = None, None
        for b in measured:
            d = frame_t - beats[b][0]
            if abs(d) <= 0.5 * 60.0 / beats[b][1] * rate and (best_d is None or abs(d) < abs(best_d)):
                best, best_d = b, d
        if best is not None:
            assigned[best].append(best_d / rate * 1000.0)
    rows, missing, extra = [], [], []   # (beat, lead, raw error ms, corrected error ms)
    for b in measured:
        errs = assigned[b]
        if not errs:
            missing.append(b)
            continue
        e = min(errs, key=abs)
        extra.extend((b, x) for x in errs if x is not e)
        lead = next((float(r["lead"]) for r in spikes if int(r["beat"]) == b), float("nan"))
        rows.append((b, lead, e, e - bias_ms))
    missing_all = sorted(set(missing) | set(no_frame))
    early = [(b, c) for b, _, _, c in rows if c < -5.0]
    late = [(b, c) for b, _, _, c in rows if c > 5.0]
    early_raw = sum(1 for _, _, e, _ in rows if e < -5.0)
    late_raw = sum(1 for _, _, e, _ in rows if e > 5.0)

    print("%s: clicks wanted %d (not scheduled %d: %s), beats without a .beats.csv frame %d, measured %d, missing %d, extra %d" % (
        os.path.basename(args.wav), len(wanted), len(not_scheduled), " ".join(map(str, not_scheduled)) or "-",
        len(no_frame), len(rows), len(missing_all), len(extra)))
    print("tempo changes: " + (", ".join("beat %d (%g->%g BPM)" % (c, beats[c - 1][1], beats[c][1]) for c in changes) or "-"))
    if missing_all:
        print("  missing: " + " ".join(map(str, missing_all)))
    print("detector bias (band_onsets on the SpikeClick waveform at 16 known samples in silence): %+.1f samples = %+.3f ms "
          "(min %+.1f, max %+.1f); corrected = raw - bias" % (bias, bias_ms, bias_min, bias_max))

    def line(name, sel):
        raw = [x[2] for x in rows if sel(x)]
        cor = [x[3] for x in rows if sel(x)]
        if not raw:
            print("  %-26s n=  0" % name)
            return float("nan"), float("nan")
        a, c = np.abs(np.array(raw)), np.abs(np.array(cor))
        print("  %-26s n=%3d  raw: mean|e| %5.2f max|e| %5.2f signed %+6.2f   corrected: mean|e| %5.2f max|e| %5.2f "
              "signed %+6.2f ms (%+.1f samples)" % (
                  name, len(raw), a.mean(), a.max(), float(np.mean(raw)), c.mean(), c.max(), float(np.mean(cor)),
                  float(np.mean(cor)) * rate / 1000.0))
        return float(c.mean()), float(c.max())

    print("attack frame - beat frame (ms; + = late):")
    overall = line("all", lambda x: True)
    line("lead 1 beat (even)", lambda x: x[1] >= 0.99)
    line("lead 0.3 beat (odd)", lambda x: x[1] < 0.99)
    jump = line("4 beats after tempo change", lambda x: x[0] in post)
    for c in changes:
        line("  after change at %d" % c, lambda x, c=c: post.get(x[0]) == c)
    stall = (float("nan"), float("nan"))
    if stalls:
        stall = line("4 beats after a stall", lambda x: x[0] in after_stall)
        for s in stalls:
            line("  after stall at %g" % s, lambda x, s=s: after_stall.get(x[0]) == s)
    if args.verbose:
        for b, lead, e, c in rows:
            print("    beat %3d lead %.1f raw %+7.2f corrected %+7.2f ms%s%s" % (
                b, lead, e, c, "  *change" if b in post else "", "  *stall" if b in after_stall else ""))
    if rows:
        signed = float(np.mean([x[3] for x in rows]))
        print("calibration check: corrected mean signed %+.2f ms (%+.1f samples); trigger +-0.5 ms: %s" % (
            signed, signed * rate / 1000.0, "beyond" if abs(signed) > 0.5 else "within"))
    if args.xcorr:
        window = int(round(args.xcorr_window_ms / 1000.0 * rate))
        lags = click_xcorr_lags(mono, rate, [beats[b][0] for b, *_ in rows], window)
        good = {f: v for f, v in lags.items() if v[1] > 0.9}
        vals, counts = np.unique([v[0] for v in good.values()], return_counts=True) if good else ([], [])
        print("XCORR (SpikeClick waveform, 2-4 kHz, +-%g ms of each beat frame; lag + = late): %d of %d measured clicks "
              "with normalised peak > 0.9; lag samples: %s" % (
                  args.xcorr_window_ms, len(good), len(rows), ", ".join("%d: %d" % (v, n) for v, n in zip(vals, counts)) or "-"))
    print("TIMING (corrected): early %d, late %d (+-5 ms), missing %d (allowed %d); raw: early %d, late %d" % (
        len(early), len(late), len(missing_all), args.allow_missing, early_raw, late_raw))
    if early:
        print("  early: " + ", ".join("%d (%+.2f ms)" % x for x in early))
    if late:
        print("  late: " + ", ".join("%d (%+.2f ms)" % x for x in late))
    ok_acc = len(rows) > 0 and overall[0] <= 2.0 and overall[1] <= 5.0 and (np.isnan(jump[1]) or jump[1] <= 5.0) and \
        (np.isnan(stall[1]) or stall[1] <= 5.0)
    ok = ok_acc and not early and not late and len(missing_all) <= args.allow_missing
    print("GATE on corrected errors (mean|e| <= 2 ms, max|e| <= 5 ms incl. the 4 beats after tempo changes%s; early 0, "
          "late 0, missing <= %d): %s" % (" and after stalls" if stalls else "", args.allow_missing, "PASS" if ok else "FAIL"))
    return 0 if ok else 1


def cmd_spike_timeline(args):
    audio, rate = read_wav(args.wav)
    base = os.path.splitext(args.wav)[0]
    beats = {int(r["beat"]): (int(r["frame"]), float(r["bpm"])) for r in read_csv(base + ".beats.csv")}
    timeline = {int(r["beat"]): int(r["timeline_ms"]) for r in read_csv(base + ".timeline.csv")}
    spikes = read_csv(base + ".spike.csv")
    mono = audio.mean(axis=1)
    ref = band_onsets(mono, rate, (900.0, 1100.0))
    test = band_onsets(mono, rate, (2800.0, 3200.0))

    # Section changes: the timeline position does not continue from the previous beat, or the tempo changes.
    changes = []
    for b in sorted(timeline):
        if b - 1 in timeline and b - 1 in beats and b in beats:
            expected = timeline[b - 1] + 60000.0 / beats[b - 1][1]
            if abs(timeline[b] - expected) > 5 or beats[b][1] != beats[b - 1][1]:
                changes.append((b, timeline[b - 1], timeline[b], beats[b - 1][1], beats[b][1]))
    post = set()
    for b, *_ in changes:
        post.update(range(b, b + 4))

    # The beat log is the conductor's callback stamps; a beat callback can arrive late (e.g. at a jump landing, where
    # two beats arrive together). Only used to find the right click pair, so replace stamps that do not fit the
    # previous beat's length by the previous beat + one beat.
    approx_frame = {}
    for b in sorted(beats):
        frame, bpm = beats[b]
        if b - 1 in approx_frame:
            expected = approx_frame[b - 1] + 60.0 / beats[b - 1][1] * rate
            if abs(frame - expected) > 0.25 * 60.0 / beats[b - 1][1] * rate:
                frame = expected
        approx_frame[b] = frame

    # Reference click of every beat (ref onset nearest to the beat's approximate frame).
    ref_of = {}
    for b in sorted(approx_frame):
        approx = approx_frame[b] / rate
        near_ref = ref[np.abs(ref - approx) <= 0.06] if len(ref) else ref
        if len(near_ref):
            ref_of[b] = near_ref[np.argmin(np.abs(near_ref - approx))]

    rows, missing, gridded = [], [], []
    for r in spikes:
        b = int(r["beat"])
        if r["scheduled"] != "1" or b not in beats:
            missing.append((b, "not scheduled"))
            continue
        rt = ref_of.get(b)
        if rt is None:
            # The music is silent at a jump landing (no ref click). Predict the beat from the previous beat's ref
            # click and tempo; these beats are listed apart, not mixed into the stats.
            if b - 1 in ref_of:
                grid = ref_of[b - 1] + 60.0 / beats[b - 1][1]
                near_test = test[np.abs(test - grid) <= args.max_pair_ms / 1000.0] if len(test) else test
                if len(near_test):
                    tt = near_test[np.argmin(np.abs(near_test - grid))]
                    gridded.append((b, float(r["lead"]), (tt - grid) * 1000.0))
                    continue
            missing.append((b, "no ref click"))
            continue
        near_test = test[np.abs(test - rt) <= args.max_pair_ms / 1000.0] if len(test) else test
        if len(near_test) == 0:
            missing.append((b, "no test click"))
            continue
        tt = near_test[np.argmin(np.abs(near_test - rt))]
        rows.append((b, float(r["lead"]), (tt - rt) * 1000.0))

    print("%s: scheduled %d, paired %d, missing %d" % (os.path.basename(args.wav), len(spikes), len(rows), len(missing)))
    for b, why in missing:
        print("  missing beat %d: %s" % (b, why))
    if changes:
        print("section changes: " + ", ".join("beat %d (%d->%d ms, %g->%g BPM)" % c for c in changes))
    if not rows:
        timing_classes(spikes, beats, ref_of, test, changes, timeline, rate, args.verbose)
        return 1
    for b, lead, e in gridded:
        print("  beat %d: no ref click (music silent at the jump landing); test click vs grid from beat %d: %+.2f ms"
              " (not in the stats)" % (b, b - 1, e))
    d = np.array([x[2] for x in rows])
    offset = args.offset_ms if args.offset_ms is not None else float(d.mean())
    print("offset used for correction: %.2f ms (%s) = %.0f samples at %d Hz" %
          (offset, "given" if args.offset_ms is not None else "mean signed error of this take", offset * rate / 1000.0, rate))

    def line(name, sel):
        raw = [x[2] for x in rows if sel(x)]
        cor = [v - offset for v in raw]
        m, mx = stats(raw)
        cm, cmx = stats(cor)
        sd = float(np.std(raw)) if raw else float("nan")
        print("  %-22s n=%3d  before: mean|e| %6.2f max|e| %6.2f signed %6.2f sd %5.2f   after: mean|e| %5.2f max|e| %5.2f ms" %
              (name, len(raw), m, mx, float(np.mean(raw)) if raw else float("nan"), sd, cm, cmx))
        return cm, cmx

    overall = line("all", lambda x: True)
    line("lead 1 beat", lambda x: x[1] >= 0.99)
    line("lead 0.3 beat", lambda x: x[1] < 0.99)
    jump = line("4 beats after change", lambda x: x[0] in post)
    if args.verbose:
        for b, lead, e in rows:
            print("    beat %3d lead %.1f err %7.2f ms%s" % (b, lead, e, "  *" if b in post else ""))
    ok = overall[0] <= 2 and overall[1] <= 5 and (np.isnan(jump[1]) or jump[1] <= 5)
    unscheduled = sum(1 for _, why in missing if why == "not scheduled")
    no_click = len(missing) - unscheduled
    print("GATE (after correction, mean <= 2 ms, max <= 5 ms, all and after changes): %s on %d measured beats; "
          "%d not scheduled, %d no click (+%d jump landings timed against the grid only)%s"
          % ("PASS" if ok else "FAIL", len(rows), unscheduled, no_click, len(gridded),
             "; conditional: not every beat was measured" if ok and missing else ""))
    early, late = timing_classes(spikes, beats, ref_of, test, changes, timeline, rate, args.verbose)
    return 1 if early or late else 0


def timing_classes(spikes, beats, ref_of, test, changes, timeline, rate, verbose):
    """Classifies every click of the test band against the beat it belongs to, also clicks far from their beat (which
    the +-40 ms pairing above never sees): early = more than 5 ms before the beat, late = more than 5 ms after, missing =
    no click. The beat time is its reference click, or (no reference: jump landing, music silent) the previous beat's
    time plus one beat. A click belongs to the first beat b with t < beat_b + 0.3 beat, so a click sounding up to
    0.7 beat early is still counted against its own beat. Returns (early, late)."""
    landings = [b for b, t0, t1, *_ in changes if b - 1 in beats and abs(t1 - (t0 + 60000.0 / beats[b - 1][1])) > 5]
    expected = {}
    for b in sorted(beats):
        if b in ref_of:
            expected[b] = ref_of[b]
        elif b - 1 in expected:
            expected[b] = expected[b - 1] + 60.0 / beats[b - 1][1]
    wanted = sorted(int(r["beat"]) for r in spikes if int(r["beat"]) in expected)
    assigned = {b: [] for b in wanted}
    for t in sorted(test):
        for b in wanted:
            if t < expected[b] + 0.3 * 60.0 / beats[b][1]:
                assigned[b].append((t - expected[b]) * 1000.0)
                break
    early, late, missing, extra = [], [], [], []
    for b in wanted:
        errs = assigned[b]
        if not errs:
            missing.append(b)
            continue
        e = min(errs, key=abs)
        extra.extend((b, x) for x in errs if x is not e)
        if e < -5.0:
            early.append((b, e))
        elif e > 5.0:
            late.append((b, e))
    after_landing = [b for b in missing if any(0 <= b - L <= 1 for L in landings)]
    other = [b for b in missing if b not in after_landing]
    print("TIMING (every test click vs its beat, +-5 ms): early %d, late %d, missing %d (%d within one beat after a jump "
          "landing at %s: %s; other: %s), extra clicks %d" % (
              len(early), len(late), len(missing), len(after_landing), "/".join(str(b) for b in landings) or "-",
              " ".join(str(b) for b in after_landing) or "-", " ".join(str(b) for b in other) or "-", len(extra)))
    if early:
        print("  early: " + ", ".join("%d (%.0f ms)" % (b, e) for b, e in early))
    if late:
        print("  late: " + ", ".join("%d (%+.0f ms)" % (b, e) for b, e in late))
    if extra and verbose:
        print("  extra: " + ", ".join("%d (%+.0f ms)" % (b, e) for b, e in extra))
    print("TIMING %s (early 0 and late 0 required)" % ("PASS" if not early and not late else "FAIL"))
    return len(early), len(late)


def rms_db(mono, a, b):
    a, b = max(0, int(round(a))), max(0, int(round(b)))
    seg = mono[a:b].astype(np.float64)
    if len(seg) == 0:
        return float("-inf")
    rms = float(np.sqrt(np.mean(seg ** 2)))
    return 20 * np.log10(rms) if rms > 0 else float("-inf")


def fmt_db(v):
    return "silent" if not np.isfinite(v) or v < -150.0 else "%.1f" % v


def silent_runs(mono, start, length, rate, win_ms=5.0, min_ms=20.0, floor_db=-70.0):
    """Runs of >= min_ms made of win_ms windows whose peak is below floor_db; returns [(offset_ms, length_ms)]."""
    win = max(1, int(round(rate * win_ms / 1000.0)))
    thr = 10 ** (floor_db / 20.0)
    start = int(round(start))
    runs, run_start, n = [], None, int(length // win)
    for i in range(n):
        seg = mono[start + i * win:start + (i + 1) * win]
        quiet = len(seg) > 0 and float(np.max(np.abs(seg))) < thr
        if quiet and run_start is None:
            run_start = i
        if (not quiet or i == n - 1) and run_start is not None:
            end = i + 1 if quiet else i
            if (end - run_start) * win_ms >= min_ms:
                runs.append((run_start * win_ms, (end - run_start) * win_ms))
            run_start = None
    return runs


def cmd_landings(args):
    audio, rate = read_wav(args.wav)
    mono = audio.mean(axis=1)
    path = os.path.splitext(args.wav)[0] + ".beats.csv"
    if not os.path.isfile(path):
        raise SystemExit("beat log not found: " + path)
    beats = {int(r["beat"]): (int(r["frame"]), float(r["bpm"])) for r in read_csv(path)}
    print("%s" % os.path.basename(args.wav))
    print("beat   bpm  delay_ms  first_half_dB  next_half_dB  prev_phrase_dB  gaps (offset+length ms after the expected boundary); rest = also silent at the same offset after beat b-4")
    for b in sorted(beats):
        if b == 0 or b % 16 != 0 or b - 1 not in beats:
            continue
        frame, bpm = beats[b]
        pf, pbpm = beats[b - 1]
        expected = pf + rate * 60.0 / pbpm
        half = 0.5 * rate * 60.0 / bpm
        first = rms_db(mono, expected, expected + half)
        nxt = rms_db(mono, expected + half, expected + 2 * half)
        prev = "n/a"
        if b - 8 in beats:
            ef, ebpm = beats[b - 8]
            prev = fmt_db(rms_db(mono, ef, ef + 0.5 * rate * 60.0 / ebpm))
        runs = silent_runs(mono, expected, rate * 60.0 / bpm, rate)
        gaps, rests = [], []
        thr = 10 ** (-70.0 / 20.0)
        for off, length in runs:
            # A rest: the window at the same offset in beats after the previous bar's downbeat (beat b-4, logged frame;
            # ms scaled by bpm[b] / bpm[b-4]) is entirely silent too. Never for a run starting within 20 ms of the
            # downbeat, nor without a b-4 stamp.
            rest = False
            if off >= 20.0 and b - 4 in beats:
                k = bpm / beats[b - 4][1]
                a0 = beats[b - 4][0] + int(round(off * k * rate / 1000.0))
                seg = mono[a0:a0 + int(round(length * k * rate / 1000.0))]
                rest = len(seg) > 0 and float(np.max(np.abs(seg))) < thr
            (rests if rest else gaps).append("%.0f+%.0f" % (off, length))
        sil = ", ".join(gaps) if gaps else "-"
        if rests:
            sil += "  (rest: " + ", ".join(rests) + ")"
        print("%4d  %4.0f  %+8.0f  %13s  %12s  %14s  %s" % (
            b, bpm, (frame - expected) / rate * 1000.0, fmt_db(first), fmt_db(nxt), prev, sil))
    if args.at_beats:
        # Arbitrary points (e.g. forced stalls): silent runs within one beat after the point, its frame interpolated
        # between the logged beats; rest = the same window one bar (4 beats) earlier is entirely silent too.
        thr = 10 ** (-70.0 / 20.0)

        def frame_at(x):
            b0 = int(np.floor(x))
            if b0 not in beats or b0 + 1 not in beats:
                return None
            return beats[b0][0] + (x - b0) * (beats[b0 + 1][0] - beats[b0][0])
        print("point  frame  silent runs >= 20 ms within one beat after the point (offset+length ms); rest = also silent 4 beats earlier")
        total_gaps = 0
        for x in [float(v) for v in args.at_beats.split(",") if v.strip()]:
            f0 = frame_at(x)
            if f0 is None:
                print("%6g  not in the beat log" % x)
                continue
            beat_len = rate * 60.0 / beats[int(np.floor(x))][1]
            gaps, rests = [], []
            for off, length in silent_runs(mono, f0, beat_len, rate):
                e = frame_at(x - 4)
                rest = False
                if e is not None:
                    a0 = int(round(e + off * rate / 1000.0))
                    seg = mono[a0:a0 + int(round(length * rate / 1000.0))]
                    rest = len(seg) > 0 and float(np.max(np.abs(seg))) < thr
                (rests if rest else gaps).append("%.0f+%.0f" % (off, length))
            total_gaps += len(gaps)
            print("%6g  %d  %s%s" % (x, int(round(f0)), ", ".join(gaps) if gaps else "-",
                                     "  (rest: " + ", ".join(rests) + ")" if rests else ""))
        print("gaps after the points: %d" % total_gaps)
    return 0


def cmd_frames(args):
    path = os.path.splitext(args.wav)[0] + ".frames.csv"
    if not os.path.isfile(path):
        raise SystemExit("frame log not found: " + path)
    raw = read_csv(path)
    forced_flags = [r.get("forced") == "1" for r in raw]
    rows = [(float(r["dt"]), float(r["beat"]), float(r["bpm"])) for r in raw]
    if any(forced_flags):
        return frames_with_forced(path, rows, forced_flags)
    # Frames before the music runs report a negative beat; start at the first frame with a beat >= 0.
    first = next((i for i, r in enumerate(rows) if r[1] >= 0), None)
    if first is None or len(rows) - first < 2:
        raise SystemExit("no frames with a running beat clock in " + path)
    backward, worst, worst_at, over, stalled = 0, 0.0, 0.0, 0, 0
    hold_ms, hold_best, hold_at = 0.0, 0.0, 0.0
    for i in range(first + 1, len(rows)):
        dt, beat, bpm = rows[i]
        delta = beat - rows[i - 1][1]
        if delta < 0:
            backward += 1
        if delta == 0 and dt > 0:
            stalled += 1
        dev = abs(delta - dt * bpm / 60.0)
        if dev > worst:
            worst, worst_at = dev, beat
        if dev > 0.05:
            over += 1
        if delta < 0.25 * dt * bpm / 60.0:
            if hold_ms == 0.0:
                hold_start = rows[i - 1][1]
            hold_ms += dt * 1000.0
            if hold_ms > hold_best:
                hold_best, hold_at = hold_ms, hold_start
        else:
            hold_ms = 0.0
    print("%s: %d frames, backward steps %d, frozen frames (delta 0) %d, max |delta beat - dt*bpm/60| %.4f beat at beat %.2f, frames over 0.05: %d, longest hold %.0f ms at beat %.2f (limit 30 ms)" % (
        os.path.basename(path), len(rows) - first, backward, stalled, worst, worst_at, over, hold_best, hold_at))
    return 1 if backward or over or hold_best > 30.0 else 0


def frames_with_forced(path, rows, forced):
    """frames for a take with forced stalls (column forced = 1 on the frame whose dt holds the Thread.Sleep): those
    frames are reported on their own and left out of the over-0.05 count, the max deviation and the hold; every other
    frame is judged as in a stall-free take (backward steps count everywhere)."""
    first = next((i for i, r in enumerate(rows) if r[1] >= 0), None)
    if first is None or len(rows) - first < 2:
        raise SystemExit("no frames with a running beat clock in " + path)
    backward, worst, worst_at, over, over_at = 0, 0.0, 0.0, 0, []
    hold_ms, hold_best, hold_at, hold_start = 0.0, 0.0, 0.0, 0.0
    for i in range(first + 1, len(rows)):
        dt, beat, bpm = rows[i]
        delta = beat - rows[i - 1][1]
        if delta < 0:
            backward += 1
        dev = abs(delta - dt * bpm / 60.0)
        if forced[i]:
            print("  forced-stall frame: dt %.0f ms, beat %.3f -> %.3f (delta %.3f, dt*bpm/60 %.3f, |dev| %.4f beat)" % (
                dt * 1000.0, rows[i - 1][1], beat, delta, dt * bpm / 60.0, dev))
            hold_ms = 0.0
            continue
        if dev > worst:
            worst, worst_at = dev, beat
        if dev > 0.05:
            over += 1
            over_at.append("%.2f (dt %.0f ms, dev %.3f)" % (beat, dt * 1000.0, dev))
        if delta < 0.25 * dt * bpm / 60.0:
            if hold_ms == 0.0:
                hold_start = rows[i - 1][1]
            hold_ms += dt * 1000.0
            if hold_ms > hold_best:
                hold_best, hold_at = hold_ms, hold_start
        else:
            hold_ms = 0.0
    print("%s: %d frames (%d forced-stall frames excluded), backward steps %d, max |delta beat - dt*bpm/60| %.4f beat at beat %.2f, "
          "frames over 0.05 outside the forced-stall frames: %d, longest hold %.0f ms at beat %.2f (limit 30 ms)" % (
              os.path.basename(path), len(rows) - first, sum(forced[first:]), backward, worst, worst_at, over, hold_best, hold_at))
    if over_at:
        print("  over: " + ", ".join(over_at[:40]))
    return 1 if backward or over or hold_best > 30.0 else 0


def cmd_tail(args):
    """Return-bus tail after StopMusic: RMS of [stop, stop+100 ms] and [stop+100 ms, end]; exit 1 if the latter is > -80 dBFS."""
    import re
    cpu = os.path.splitext(args.wav)[0] + ".cpu.txt"
    if not os.path.isfile(cpu):
        raise SystemExit("cpu.txt not found: " + cpu)
    text = open(cpu).read()
    match = re.search(r"STOP frame (\d+)", text)
    if not match:
        raise SystemExit("no 'STOP frame N' in " + cpu + " (record with stopTailSeconds > 0)")
    stop = int(match.group(1))
    restart = re.search(r"RESTART frame (\d+)", text)
    audio, rate = read_wav(args.wav)
    mono = audio.mean(axis=1)
    split = stop + int(0.1 * rate)
    if restart and int(restart.group(1)) <= stop:
        print("RESTART frame %s is not after STOP frame %d in %s" % (restart.group(1), stop, cpu))
        return 2
    head = rms_db(mono, stop, split)
    end = int(restart.group(1)) if restart else len(mono)  # the tail ends where a restart begins
    if end <= split:
        print("tail window is empty (end frame %d <= stop + 100 ms = %d); record with a longer stopTailSeconds" % (end, split))
        return 2
    tail = rms_db(mono, split, end)
    print("%s: stop frame %d (%.2f s), tail end %.2f s" % (args.wav, stop, stop / rate, end / rate))
    print("RMS [stop, stop+100 ms]      %s dBFS" % fmt_db(head))
    print("RMS [stop+100 ms, end]       %s dBFS (limit -80)" % fmt_db(tail))
    status = 0 if tail <= -80.0 else 1
    print("TAIL %s" % ("PASS" if status == 0 else "FAIL"))
    beats2 = os.path.splitext(args.wav)[0] + ".beats2.csv"
    if os.path.isfile(beats2):
        def first4(path):
            rows = list(csv.DictReader(open(path, newline="")))
            return int(rows[0]["frame"]), int(rows[4]["frame"])
        a = first4(os.path.splitext(args.wav)[0] + ".beats.csv")
        b = first4(beats2)
        first, again = rms_db(mono, *a), rms_db(mono, *b)
        print("first 4 beats at start  %.2f dBFS; first 4 beats after restart %.2f dBFS; diff %.2f dB (limit 1 dB)" % (first, again, again - first))
        if abs(again - first) > 1.0:
            status = 1
    return status


BANDS = (("<300", None, 300.0), ("300-2k", 300.0, 2000.0), (">2k", 2000.0, None))


def band_signals(wav_path):
    """(mono signal per band, rate) for the three BANDS."""
    from scipy import signal
    audio, rate = read_wav(wav_path)
    mono = audio.mean(axis=1).astype(np.float64)
    out = []
    for _, lo, hi in BANDS:
        if lo is None:
            sos = signal.butter(4, hi, btype="lowpass", fs=rate, output="sos")
        elif hi is None:
            sos = signal.butter(4, lo, btype="highpass", fs=rate, output="sos")
        else:
            sos = signal.butter(4, [lo, hi], btype="bandpass", fs=rate, output="sos")
        out.append(signal.sosfiltfilt(sos, mono))
    return out, rate


def band_levels(signals, a, b):
    return [rms_db(s, a, b) for s in signals]


