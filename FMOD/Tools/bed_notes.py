"""
Writes Assets/Scripts/Audio/BedNotes.g.cs: where the adaptive bed's variation patterns and combo bells sound
inside a 4-bar phrase, so the visuals (BedLayerVisuals) pulse on the notes FMOD plays.
It only reads the pattern functions of bed_variation.py and bed_combo.py (no FMOD project changes), so run it
again whenever those patterns change:  python bed_notes.py
"""
import os

import bed_combo
import bed_variation as var

HERE = os.path.dirname(os.path.abspath(__file__))
CS_PATH = os.path.join(HERE, "..", "..", "Assets", "Scripts", "Audio", "BedNotes.g.cs")
BARS = 4


def phrase(pattern):
    """(beat in phrase, midi) for every bar of a phrase; patterns return (beat, midi, ...) or (beat, volume)."""
    out = []
    for bar in range(BARS):
        for n in pattern(bar):
            midi = n[1] if len(n) > 2 else 0
            out.append((bar * 4 + n[0], midi))
    return sorted(set(out))


def bells(bar):
    # Same timing as bed_combo.build(): one bell per off-beat, notes from the bar's chord.
    return [(i + 0.5, m, 0, 0) for i, m in enumerate(bed_combo.BARS[bar]["bells"])]


def array(name, notes, doc):
    entries = ", ".join(f"new Note({b}f, {m})" for b, m in notes)
    return f"    /// <summary>{doc}</summary>\n    public static readonly Note[] {name} = {{ {entries} }};\n"


def uses(name, key):
    lo, hi = var.RANGES[key]
    return f"    public static bool {name}(int variation) => variation >= {lo} && variation <= {hi};\n"


def main():
    parts = [
        array("BassDrive", phrase(var.bass_b), "Bass B: 8th-note drive with octave pops."),
        array("BassWalk", phrase(var.bass_c), "Bass C: syncopated root, fifth and a walk into the next chord."),
        array("PluckArpeggio", phrase(var.pluck_b), "Pluck B: straight 8th arpeggio."),
        array("PluckStabs", phrase(var.pluck_c), "Pluck C: tresillo triad stabs (one entry per voice)."),
        array("Ghosts", phrase(var.ghosts), "Quiet snare ghosts."),
        array("Fill", phrase(var.fill), "Bar 4 16th snare crescendo into the next phrase."),
        array("ComboBells", phrase(bells), "Combo 3 formant bells on the off-beats."),
        "\n",
        uses("UsesBassDrive", "bassB"), uses("UsesBassWalk", "bassC"),
        uses("UsesPluckArpeggio", "pluckB"), uses("UsesPluckStabs", "pluckC"),
        uses("UsesGhosts", "drumsGhost"), uses("UsesFill", "drumsFill"),
        uses("UsesOriginalPluck", "pluckA"),
    ]
    cs = (
        "// Generated by FMOD/Tools/bed_notes.py from bed_variation.py and bed_combo.py - edit those, not this.\n"
        "// Note positions of the adaptive bed's variation patterns and combo bells within a 4-bar phrase.\n"
        "public static class BedNotes\n"
        "{\n"
        "    public readonly struct Note\n"
        "    {\n"
        "        /// <summary>Beat within the 4-bar phrase (0..16).</summary>\n"
        "        public readonly float Beat;\n"
        "        /// <summary>MIDI note (0 for drums).</summary>\n"
        "        public readonly int Midi;\n\n"
        "        public Note(float beat, int midi) { Beat = beat; Midi = midi; }\n"
        "    }\n\n" + "".join(parts) + "}\n")
    with open(CS_PATH, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(cs)
    print("->", os.path.normpath(CS_PATH))


if __name__ == "__main__":
    main()
