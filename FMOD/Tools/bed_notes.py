"""
Writes Assets/Scripts/Audio/BedNotes.g.cs: where the adaptive bed's variation patterns and combo bells sound
inside a 4-bar phrase, so the visuals (BedLayerVisuals) pulse on the notes the music plays.
Bass, pluck and combo bells come from the pattern clips (pattern_bed.py, what the PatternScheduler plays); the snare
ghosts / fill (drums, not migrated yet) still from bed_variation.py. No FMOD project changes; run it again whenever those
patterns change:  python -I FMOD/Tools/bed_notes.py
The output keeps its old shape and header byte for byte (the visuals read it); InstrumentCoverageTests pins it to the
pattern data.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # so `python -I` (isolated mode) still finds the modules next to this file

import bed_variation as var  # noqa: E402
import patterns  # noqa: E402

CS_PATH = os.path.join(HERE, "..", "..", "Assets", "Scripts", "Audio", "BedNotes.g.cs")
BARS = 4


def phrase(pattern):
    """(beat in phrase, midi) for every bar of a phrase; drum patterns return (beat, volume) (MIDI 0)."""
    out = []
    for bar in range(BARS):
        for n in pattern(bar):
            midi = n[1] if len(n) > 2 else 0
            out.append((bar * 4 + n[0], midi))
    return sorted(set(out))


def clips():
    return {c.name: c for c in patterns.collect()[1]}


def clip_notes(name):
    """(beat in phrase, midi) of a pattern clip, one entry per voice."""
    return sorted({(n.beat, n.midi) for n in clips()[name].notes})


def array(name, notes, doc):
    entries = ", ".join(f"new Note({b}f, {m})" for b, m in notes)
    return f"    /// <summary>{doc}</summary>\n    public static readonly Note[] {name} = {{ {entries} }};\n"


def uses_range(name, lo, hi):
    return f"    public static bool {name}(int variation) => variation >= {lo} && variation <= {hi};\n"


def uses(name, key):
    return uses_range(name, *var.RANGES[key])


def uses_clip(name, clip):
    return uses_range(name, *clips()[clip].variation)


def main():
    assert clips()["PluckA1"].variation == clips()["PluckA2"].variation
    parts = [
        array("BassDrive", clip_notes("BassDrive"), "Bass B: 8th-note drive with octave pops."),
        array("BassWalk", clip_notes("BassWalk"), "Bass C: syncopated root, fifth and a walk into the next chord."),
        array("PluckArpeggio", clip_notes("PluckArpeggio"), "Pluck B: straight 8th arpeggio."),
        array("PluckStabs", clip_notes("PluckStabs"), "Pluck C: tresillo triad stabs (one entry per voice)."),
        array("Ghosts", phrase(var.ghosts), "Quiet snare ghosts."),
        array("Fill", phrase(var.fill), "Bar 4 16th snare crescendo into the next phrase."),
        array("ComboBells", clip_notes("ComboBells"), "Combo 3 formant bells on the off-beats."),
        "\n",
        uses_clip("UsesBassDrive", "BassDrive"), uses_clip("UsesBassWalk", "BassWalk"),
        uses_clip("UsesPluckArpeggio", "PluckArpeggio"), uses_clip("UsesPluckStabs", "PluckStabs"),
        uses("UsesGhosts", "drumsGhost"), uses("UsesFill", "drumsFill"),
        uses_clip("UsesOriginalPluck", "PluckA1"),
    ]
    cs = (
        "// Generated by FMOD/Tools/bed_notes.py from bed_variation.py and bed_combo.py - edit those, not this.\n"
        "// Note positions of the adaptive bed's variation patterns and combo bells within a 4-bar phrase.\n"
        "public static class BedNotes\n"
        "{\n"
        "    public readonly struct Note\n"
        "    {\n"
        "        /// <summary>Beat within the 4-bar phrase (0..16).</summary>\n"
        "        public readonly float Beat;\n"
        "        /// <summary>MIDI note (0 for drums).</summary>\n"
        "        public readonly int Midi;\n\n"
        "        public Note(float beat, int midi) { Beat = beat; Midi = midi; }\n"
        "    }\n\n" + "".join(parts) + "}\n")
    # The header above is kept byte for byte (the file must not change); the bass / pluck / bells data now come from
    # pattern_bed.py, and the old generators keep the same values until their timeline tracks are deleted.
    with open(CS_PATH, "w", encoding="utf-8", newline="\r\n") as f:
        f.write(cs)
    print("->", os.path.normpath(CS_PATH))


if __name__ == "__main__":
    main()
