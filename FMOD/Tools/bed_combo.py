"""
Adaptive bed, axis 2: combo layers and the hurt dip for event:/Music/ChordPulseGame (Docs/AdaptiveAudioPlan.md 8-2).

Writes bed_combo.js next to this file. Run it on the FMOD project (FMOD Studio closed) with
    fmodstudiocl.exe -script FMOD/Tools/bed_combo.js FMOD/ChordPulse/ChordPulse.fspro
It is idempotent: it removes the "Combo *" tracks and its hurt effects from an earlier run.

Game parameters:
- Combo 0..3: kill streak level, changed by Unity only on bar lines (instruments are gated by conditions).
    1+  16th closed hats on the "e" and "a" of every beat          (track "Combo hats", in Music Bed)
    2+  airy glass pad, one high chord per bar                      (track "Combo pad", in Harmony)
    3   formant-bell arpeggio on the off-beats, above the pluck     (track "Combo bells", in Harmony)
  Pad and bells sit in Harmony, so kill chords duck them like the pluck.
- Hurt 0..1: Unity snaps it to 1 when the core is hit; FMOD's seek speed brings it back to 0 in ~0.6 s.
  Cutting the lows (3-band EQ, low band 0 -> -24 dB below 300 Hz) and a gain dip (-4 dB) on Music Bed make
  the hit "knock the wind out" of the accompaniment. It works on the lows, so it never fights the Danger
  low-pass from bed_tension.py.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SECTIONS = []
_t = 0.0
for _bpm in (108, 116, 124, 132):
    SECTIONS.append((_t, _bpm))
    _t += 32 * 60.0 / _bpm
BARS_PER_SECTION = 8

HAT = ("Pallor_ClosedHat_Synthpop_v110.wav", 0)
PAD = ("Synth/AT20V_GlassPad_A3_v90.wav", 57)
BELLS = [("Synth/ATFS1_FormantBells_C5_v100.wav", 72), ("Synth/ATFS1_FormantBells_G5_v100.wav", 79)]

# Per bar of the phrase (C, Am, F, G): pad voicing (above the tension strings) and bell arpeggio (off-beats).
BARS = [
    dict(pad=(67, 72, 76), bells=(76, 79, 84, 79)),   # C:  G4 C5 E5 / E5 G5 C6 G5
    dict(pad=(69, 72, 76), bells=(76, 81, 84, 81)),   # Am: A4 C5 E5 / E5 A5 C6 A5
    dict(pad=(69, 72, 77), bells=(77, 81, 84, 81)),   # F:  A4 C5 F5 / F5 A5 C6 A5
    dict(pad=(67, 71, 74), bells=(74, 79, 83, 79)),   # G:  G4 B4 D5 / D5 G5 B5 G5
]
LEVEL = {"hats": -16.0, "pad": -27.0, "bells": -24.0}     # instrument volume (dB); set from offline renders
HURT_LOW_CUT = [(0.0, 0.0), (0.3, -8.0), (1.0, -24.0)]   # 3-band EQ low band gain (dB), crossover 300 Hz
HURT_GAIN = [(0.0, 0.0), (1.0, -4.0)]


def pick(table, midi):
    sample = min(table, key=lambda s: (abs(midi - s[1]), -s[1]))
    return sample, midi - sample[1]


def build():
    notes = []
    for start, bpm in SECTIONS:
        beat = 60.0 / bpm
        for bar in range(BARS_PER_SECTION):
            t0 = start + bar * 4 * beat
            b = BARS[bar % 4]
            for i in range(4):
                for sub in (0.25, 0.75):
                    accent = -2.0 if sub == 0.75 else 0.0
                    notes.append(dict(track="hats", combo=1, file=HAT[0], pitch=0, start=t0 + (i + sub) * beat,
                                      length=0.2 * beat, volume=LEVEL["hats"] + accent))
            for m in b["pad"]:
                s, p = pick([PAD], m)
                notes.append(dict(track="pad", combo=2, file=s[0], pitch=p, start=t0, length=4 * beat,
                                  volume=LEVEL["pad"]))
            for i, m in enumerate(b["bells"]):
                s, p = pick(BELLS, m)
                notes.append(dict(track="bells", combo=3, file=s[0], pitch=p, start=t0 + (i + 0.5) * beat,
                                  length=0.9 * beat, volume=LEVEL["bells"] - (0 if i == 0 else 2.0)))
    for n in notes:
        assert -12 <= n["pitch"] <= 24, n
        n["start"] = round(n["start"], 6)
        n["length"] = round(n["length"], 6)
    return notes


JS_TEMPLATE = r"""// Generated by FMOD/Tools/bed_combo.py - edit the Python file, not this one.
var NOTES = __NOTES__;
var HURT_LOW_CUT = __HP__;
var HURT_GAIN = __GAIN__;

function log(m) { console.log("[combo] " + m); }
var project = studio.project;
var ev = project.lookup("event:/Music/ChordPulseGame");
var assetsRoot = project.filePath.replace(/[^\/\\]+$/, "") + "Assets/";

function parameter(name, max, seekUp, seekDown) {
    var preset = project.lookup("parameter:/" + name);
    if (!preset) {
        project.workspace.addGameParameter({ name: name, type: project.parameterType.User, min: 0, max: max });
        preset = project.lookup("parameter:/" + name);
        log("created parameter " + name);
    }
    var p = preset.parameter;
    p.minimum = 0; p.maximum = max; p.initialValue = 0;
    if (seekUp !== undefined) { p.seekSpeedAsymmetric = true; p.seekSpeed = seekUp; p.seekSpeedDescending = seekDown; }
    var has = false;
    ev.parameters.forEach(function (x) { if (x.preset && (x.preset.id === p.id || x.preset.id === preset.id)) has = true; });
    if (!has) { ev.addGameParameter(preset); log("added " + name + " to event"); }
    return preset;
}
var combo = parameter("Combo", 3);
var hurt = parameter("Hurt", 1, 20.0, 1.6);   // Unity snaps it to 1; it falls back in ~0.6 s

function groupByName(name) {
    var found = null;
    ev.groupTracks.forEach(function (t) { if (t.mixerGroup.name === name) found = t; });
    if (!found) throw "track not found: " + name;
    return found;
}
var musicBed = groupByName("Music Bed").mixerGroup;
var harmony = groupByName("Harmony").mixerGroup;

function automatedBy(effect, preset) {
    var hit = false;
    effect.automators.forEach(function (a) {
        a.automationCurves.forEach(function (c) { if (c.parameter && c.parameter.id === preset.parameter.id) hit = true; });
    });
    return hit;
}

// --- undo an earlier run ---
var old = [];
ev.groupTracks.forEach(function (t) { if (/^Combo /.test(t.mixerGroup.name)) old.push(t); });
old.forEach(function (t) { project.deleteObject(t); });
musicBed.effectChain.effects.slice().forEach(function (e) { if (automatedBy(e, hurt)) project.deleteObject(e); });
if (old.length) log("removed " + old.length + " old combo tracks");

function automate(owner, property, preset, points) {
    var automator = owner.addAutomator(property);
    var curve = automator.addAutomationCurve(preset.parameter);
    points.forEach(function (pt) { curve.addAutomationPoint(pt[0], pt[1]); });
}
// A 3-band EQ rather than a high-pass: at 0 dB its bands sum flat, so it is transparent when unhurt.
var eq = musicBed.effectChain.addEffect("ThreeEQEffect");
eq.lowGain = 0; eq.midGain = 0; eq.highGain = 0; eq.lowCrossover = 300; eq.highCrossover = 4000;
automate(eq, "lowGain", hurt, HURT_LOW_CUT);
var gain = musicBed.effectChain.addEffect("GainEffect");
gain.gain = 0;
automate(gain, "gain", hurt, HURT_GAIN);

var files = {};
function audioFile(rel) {
    if (files[rel]) return files[rel];
    var found = null;
    project.model.AudioFile.findInstances().forEach(function (a) {
        if (a.isValid && a.masterAssetFolder && a.length > 0 && a.assetPath === rel) found = a;
    });
    if (!found) { found = project.importAudioFile(assetsRoot + rel); log("imported " + rel); }
    if (!found) throw "could not import " + rel;
    files[rel] = found;
    return found;
}
function addTrack(name, output) {
    var t = project.create("GroupTrack");
    t.mixerGroup.name = name;
    t.mixerGroup.output = output;
    ev.relationships.groupTracks.add(t);
    return t;
}
var tracks = {
    hats: addTrack("Combo hats", musicBed),
    pad: addTrack("Combo pad", harmony),
    bells: addTrack("Combo bells", harmony),
};
var padHp = tracks.pad.mixerGroup.effectChain.addEffect("HighpassEffect");
padHp.cutoff = 300; padHp.resonance = 1;

var envelope = { hats: [1, 30], pad: [300, 500], bells: [2, 250] };
NOTES.forEach(function (n) {
    var s = tracks[n.track].addSound(ev.timeline, "SingleSound", n.start, n.length);
    s.audioFile = audioFile(n.file);
    s.pitch = n.pitch;
    s.volume = n.volume;
    s.addParameterCondition(combo, n.combo - 0.4, 3.4);
    var env = project.create("ADSRModulator");
    env.nameOfPropertyBeingModulated = "volume";
    env.attackTime = envelope[n.track][0]; env.releaseTime = envelope[n.track][1];
    env.objectBeingModulated = s;
});
log("placed " + NOTES.length + " notes");
project.save();
log("saved");
"""


def main():
    notes = build()
    js = (JS_TEMPLATE.replace("__NOTES__", json.dumps(notes)).replace("__HP__", json.dumps(HURT_LOW_CUT))
          .replace("__GAIN__", json.dumps(HURT_GAIN)))
    with open(os.path.join(HERE, "bed_combo.js"), "w", encoding="utf-8") as f:
        f.write(js)
    counts = {}
    for n in notes:
        counts[n["track"]] = counts.get(n["track"], 0) + 1
    print(counts, "->", "bed_combo.js")


if __name__ == "__main__":
    main()
