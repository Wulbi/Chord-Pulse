"""
Cleanup of the music event's legacy timeline layers (stages 3-8 plan, Task 15b). Every layer they held now plays as a
scheduled one-shot (event:/Inst/*, patterns.py / instruments.py) on the Unity clock, and the game no longer starts
event:/Music/ChordPulseGame. This removes from the FMOD project:

- every track in patterns.LEGACY_TRACKS (the 37 migrated timeline tracks; the list stays in patterns.py, read here);
- the event's parameters EVENT_PARAMETERS and the event's proxies of the global Tension / Danger / Hurt, plus any
  automation in the event still bound to one of them (the Music Bed group's MusicMix volume curve). A preset that no
  event uses any more is deleted too; one still used elsewhere (Fever: event:/Music/ChordPulsePreview) stays;
- the global parameter LegacyLayers;
- the in-event Harmony and Feature groups, then return:/Harmony Duck and return:/Feature Duck - only when nothing is left
  in them; otherwise the script stops (nothing saved) and prints what remains.

Kept: the Spike ref track, NextSection, SpikeRef, the tempo / transition markers and the rest of the timeline, the Music
Bed group, and event:/Music/ChordPulsePreview.

Before anything global or mixer-side is deleted, nothing outside the music event may use it: `python cleanup_music.py`
lists every Metadata file that names LegacyLayers or either return (refuses to write the script if one is outside the
music event), and the script itself stops if a condition, automation curve or parameter proxy still uses LegacyLayers,
or a send still feeds a return, once the event's own objects are gone.

Writes cleanup_music.js next to this file. Run order (Docs/AdaptiveAudioPlan.md 8-10): instruments.js -> mixer.js ->
cleanup_music.js (once) -> build as a SEPARATE command, FMOD Studio closed:
    python -I FMOD/Tools/cleanup_music.py
    fmodstudiocl.exe -script FMOD/Tools/cleanup_music.js FMOD/ChordPulse/ChordPulse.fspro
    fmodstudiocl.exe -build FMOD/ChordPulse/ChordPulse.fspro
Re-runnable: a second run finds nothing, logs "nothing to do" and does not save.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import kill_oneshots  # noqa: E402  (write_if_different)
import patterns  # noqa: E402

JS_PATH = os.path.join(HERE, "cleanup_music.js")
METADATA = os.path.join(HERE, "..", "ChordPulse", "Metadata")
EVENT = "event:/Music/ChordPulseGame"
EVENT_XML = "{3d468f15-e95b-49c7-89e5-8b0245d9bf6d}.xml"
EVENT_PARAMETERS = ["BedStyle", "Variation", "Combo", "Intensity", "FeatureLoop", "Fever", "FeverBuild", "FeverImpact",
                    "FeverOutro", "MusicMix"]
GLOBAL_PROXIES = ["Tension", "Danger", "Hurt"]   # the presets stay (global, used by the mixer buses); only the event's proxies go
GLOBAL_PARAMETER = "LegacyLayers"
GROUPS = ["Harmony", "Feature"]
RETURNS = ["Harmony Duck", "Feature Duck"]
LEGACY_TRACK_COUNT = 37   # 13 bed (Task 11) + 10 drums (12) + 6 feature (13) + 8 fever (14)


def tracks():
    names = patterns.LEGACY_TRACKS
    assert len(names) == len(set(names)) == LEGACY_TRACK_COUNT, names
    assert "Spike ref" not in names and not set(names) & set(GROUPS + ["Music Bed"]), names
    return names


def _objects(path):
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    return text, re.findall(r'<object class="([A-Za-z]+)" id="(\{[0-9a-f-]+\})">\s*<property name="name">\s*<value>([^<]*)</value>', text)


def reference_report():
    """{name: (own ids, [files outside the music event and the object's own file that name one of those ids])}, for
    LegacyLayers (preset + its GameParameter) and the two returns. A missing object (already deleted) has no ids."""
    files = []
    for d, _, names in os.walk(METADATA):
        files += [os.path.join(d, n) for n in names if n.endswith(".xml")]
    texts = {p: open(p, "r", encoding="utf-8").read() for p in files}
    wanted = {GLOBAL_PARAMETER: ("ParameterPreset", "ParameterPreset")}
    wanted.update({r: ("MixerReturn", "Return") for r in RETURNS})
    out = {}
    for name, (cls, folder) in wanted.items():
        ids, own = [], None
        for p in files:
            if os.path.basename(os.path.dirname(p)) != folder:
                continue
            for c, i, n in _objects(p)[1]:
                if c == cls and n == name:
                    own = p
                    ids.append(i)
                    if cls == "ParameterPreset":
                        m = re.search(r'<relationship name="parameter">\s*<destination>(\{[0-9a-f-]+\})', texts[p])
                        ids.append(m.group(1))
        users = sorted(os.path.relpath(p, METADATA) for p, t in texts.items()
                       if p != own and os.path.basename(p) != EVENT_XML and any(i in t for i in ids))
        out[name] = (ids, users)
    return out


JS_TEMPLATE = r"""// Generated by FMOD/Tools/cleanup_music.py - edit the Python file, not this one.
// Removes the legacy timeline layers, their parameters, LegacyLayers and the two Duck returns (re-runnable).
var TRACKS = __TRACKS__;
var EVENT_PARAMETERS = __EVENT_PARAMETERS__;
var GLOBAL_PROXIES = __GLOBAL_PROXIES__;
var GLOBAL_PARAMETER = "__GLOBAL_PARAMETER__";
var GROUPS = __GROUPS__;
var RETURNS = __RETURNS__;

function log(m) { console.log("[cleanup-music] " + m); }
var project = studio.project;
var ev = project.lookup("__EVENT__");
if (!ev) throw "__EVENT__ not found";
var counts = { tracks: 0, notes: 0, automators: 0, groups: 0, proxies: 0, presets: 0, returns: 0, globals: 0 };
function valid(list) { return list.filter(function (x) { return x && x.isValid; }); }
function same(a, b) { return a && b && a.id === b.id; }
function soundsOf(t) { return t.modules.filter(function (m) { return m.entity === "SingleSound"; }).length; }
function trackNamed(name) {
    var found = ev.groupTracks.filter(function (t) { return t.mixerGroup && t.mixerGroup.name === name; });
    if (found.length > 1) throw "track " + name + ": " + found.length + " tracks with that name";
    return found[0] || null;
}
function presetOf(name) {
    var p = project.lookup("parameter:/" + name);
    return p && p.isValid ? p : null;
}
// A proxy / condition / curve may point at the preset's GameParameter (usual) or the preset itself.
function isParam(x, preset) { return x && (x.id === preset.id || (preset.parameter && x.id === preset.parameter.id)); }

var before = { sounds: 0, tracks: ev.groupTracks.length, proxies: ev.parameters.length };
ev.groupTracks.forEach(function (t) { before.sounds += soundsOf(t); });
log("before: tracks " + before.tracks + ", SingleSound " + before.sounds + ", event parameters " + before.proxies);

// --- 1. the legacy tracks ---
TRACKS.forEach(function (name) {
    var t = trackNamed(name);
    if (!t) return;
    var n = 0;
    t.modules.slice().forEach(function (m) { if (m.entity === "SingleSound") n++; project.deleteObject(m); });
    var g = t.mixerGroup;
    project.deleteObject(t);
    if (g && g.isValid) project.deleteObject(g);
    counts.tracks++;
    counts.notes += n;
    log("deleted track " + name + " (" + n + " notes)");
});

// --- 2. Harmony / Feature groups: only when empty ---
var remaining = [];
GROUPS.forEach(function (name) {
    var t = trackNamed(name);
    if (!t) return;
    if (t.modules.length) remaining.push(name + ": " + t.modules.length + " modules on the group itself");
    ev.groupTracks.forEach(function (x) {
        if (x.mixerGroup && same(x.mixerGroup.output, t.mixerGroup)) remaining.push(name + " <- track " + x.mixerGroup.name + " (" + soundsOf(x) + " notes)");
    });
});
if (remaining.length) {
    remaining.forEach(log);
    throw "Harmony / Feature group not empty: nothing deleted, nothing saved (tracks listed above)";
}
GROUPS.forEach(function (name) {
    var t = trackNamed(name);
    if (!t) return;
    var g = t.mixerGroup;
    project.deleteObject(t);
    if (g && g.isValid) project.deleteObject(g);
    counts.groups++;
    log("deleted group " + name);
});

// --- 3. event parameters (and the event's proxies of Tension / Danger / Hurt) ---
function automatorsIn(fn) {
    // every automator on the event's groups, their effects and the master
    var list = [];
    var mixers = ev.groupTracks.map(function (t) { return t.mixerGroup; });
    if (ev.mixer && ev.mixer.masterBus) mixers.push(ev.mixer.masterBus);
    mixers.forEach(function (g) {
        if (!g) return;
        g.automators.forEach(function (a) { list.push(a); });
        g.effectChain.effects.forEach(function (e) { (e.automators || []).forEach(function (a) { list.push(a); }); });
    });
    list.forEach(fn);
}
EVENT_PARAMETERS.concat(GLOBAL_PROXIES).forEach(function (name) {
    var preset = presetOf(name);
    if (!preset) return;
    automatorsIn(function (a) {
        if (!a.isValid) return;
        var hit = a.automationCurves.some(function (c) { return isParam(c.parameter, preset); });
        if (!hit) return;
        log("deleted automation of " + a.nameOfPropertyBeingAutomated + " by " + name);
        project.deleteObject(a);
        counts.automators++;
    });
    var left = [];
    ev.groupTracks.forEach(function (t) {
        t.modules.forEach(function (m) {
            (m.triggerConditions || []).forEach(function (c) { if (isParam(c.parameter, preset)) left.push(t.mixerGroup.name); });
        });
    });
    if (left.length) throw name + ": " + left.length + " notes outside the legacy tracks still use it (" + left.slice(0, 5).join(", ") + ")";
    ev.parameters.slice().forEach(function (p) {
        if (!isParam(p.preset, preset)) return;
        project.deleteObject(p);
        counts.proxies++;
        log("removed " + name + " from the event");
    });
});
// presets no event uses any more (not the global Tension / Danger / Hurt)
var proxies = valid(project.model.ParameterProxy.findInstances());
EVENT_PARAMETERS.forEach(function (name) {
    var preset = presetOf(name);
    if (!preset) return;
    var users = proxies.filter(function (p) { return isParam(p.preset, preset); });
    if (users.length) { log("kept preset " + name + ": still used by " + users.length + " other event(s)"); return; }
    project.deleteObject(preset);
    counts.presets++;
    log("deleted preset " + name);
});

// --- 4. returns: only when no send feeds them ---
var sends = valid(project.model.MixerSend.findInstances());
RETURNS.forEach(function (name) {
    var r = null;
    valid(project.model.MixerReturn.findInstances()).forEach(function (x) { if (x.name === name) r = x; });
    if (!r) return;
    var feeding = sends.filter(function (s) { return same(s.mixerReturn, r); });
    if (feeding.length) throw "return:/" + name + " is still fed by " + feeding.length + " send(s) outside the music event's Harmony / Feature groups: nothing saved";
    project.deleteObject(r);
    counts.returns++;
    log("deleted return:/" + name);
});

// --- 5. the global LegacyLayers: only when nothing uses it ---
var legacy = presetOf(GLOBAL_PARAMETER);
if (legacy) {
    var users = [];
    valid(project.model.ParameterProxy.findInstances()).forEach(function (p) { if (isParam(p.preset, legacy)) users.push("proxy"); });
    valid(project.model.ParameterCondition.findInstances()).forEach(function (c) { if (isParam(c.parameter, legacy)) users.push("condition"); });
    valid(project.model.AutomationCurve.findInstances()).forEach(function (c) { if (isParam(c.parameter, legacy)) users.push("automation"); });
    if (users.length) throw GLOBAL_PARAMETER + " still used (" + users.length + ": " + users.slice(0, 5).join(", ") + "): nothing saved";
    project.deleteObject(legacy);
    counts.globals++;
    log("deleted parameter:/" + GLOBAL_PARAMETER);
}

var after = { sounds: 0, tracks: ev.groupTracks.length, proxies: ev.parameters.length };
ev.groupTracks.forEach(function (t) { after.sounds += soundsOf(t); });
log("after: tracks " + after.tracks + " (" + ev.groupTracks.map(function (t) { return t.mixerGroup.name; }).join(", ") +
    "), SingleSound " + after.sounds + ", event parameters " + after.proxies);
var total = 0;
Object.keys(counts).forEach(function (k) { if (k !== "notes") total += counts[k]; });
log("deleted: " + JSON.stringify(counts));
if (total) { project.save(); log("saved"); } else log("nothing to do");
"""


def js_text():
    return (JS_TEMPLATE.replace("__TRACKS__", json.dumps(tracks()))
            .replace("__EVENT_PARAMETERS__", json.dumps(EVENT_PARAMETERS))
            .replace("__GLOBAL_PROXIES__", json.dumps(GLOBAL_PROXIES))
            .replace("__GLOBAL_PARAMETER__", GLOBAL_PARAMETER)
            .replace("__GROUPS__", json.dumps(GROUPS))
            .replace("__RETURNS__", json.dumps(RETURNS))
            .replace("__EVENT__", EVENT))


def main():
    outside = False
    for name, (ids, users) in reference_report().items():
        if not ids:
            print(f"{name}: not in the project")
            continue
        print(f"{name} {' '.join(ids)}: used outside the music event by {users if users else 'nothing'}")
        outside = outside or bool(users)
    if outside:
        print("STOP: something outside the music event uses one of these; cleanup_music.js not written")
        sys.exit(1)
    changed = kill_oneshots.write_if_different(JS_PATH, js_text())
    print("cleanup_music.js", "written" if changed else "unchanged", "-", len(tracks()), "tracks,",
          len(EVENT_PARAMETERS), "event parameters,", GLOBAL_PARAMETER + ",", len(RETURNS), "returns")


if __name__ == "__main__":
    main()
