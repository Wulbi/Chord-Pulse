"""
Removes event:/Music/ChordPulseGame from the FMOD project (unity-music-clock plan, Task 8). The game no longer starts it:
the music clock is Unity's MusicTransport and every layer is a scheduled event:/Inst/* one-shot. After Task 15b's
cleanup_music.js the event only held the "Spike ref" track (128 timeline clicks for the old Task 3 spike test), which
the capture no longer uses (the spike clicks are event:/Inst/*/SpikeClick one-shots measured against the clock).

What the generated script does:
- counts the event's SingleSound notes per track; if any note sits on a track other than "Spike ref", it deletes nothing,
  saves nothing, prints the tracks and stops;
- deletes the event (its tracks, markers, parameter proxies and mixer go with it);
- deletes the presets of PARAMETERS (NextSection, SpikeRef), each only if no other ParameterProxy, ParameterCondition or
  AutomationCurve in the project still uses it once the event is gone;
- does nothing when the event is already gone (re-runnable: logs "nothing to do" and does not save).
event:/Music/ChordPulsePreview is not touched.

Before writing the script, `python remove_music_event.py` lists every Metadata file that names one of the presets
(preset or its GameParameter id); a user outside the music event's XML and the preset's own file stops it (same check as
cleanup_music.py).

Run (FMOD Studio closed; build as a SEPARATE command, then copy the banks to Assets/StreamingAssets):
    python -I FMOD/Tools/remove_music_event.py
    fmodstudiocl.exe -script FMOD/Tools/remove_music_event.js FMOD/ChordPulse/ChordPulse.fspro
    fmodstudiocl.exe -build FMOD/ChordPulse/ChordPulse.fspro
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import kill_oneshots  # noqa: E402  (write_if_different)

JS_PATH = os.path.join(HERE, "remove_music_event.js")
METADATA = os.path.join(HERE, "..", "ChordPulse", "Metadata")
EVENT = "event:/Music/ChordPulseGame"
EVENT_XML = "{3d468f15-e95b-49c7-89e5-8b0245d9bf6d}.xml"
KEEP_TRACK = "Spike ref"
PARAMETERS = ["NextSection", "SpikeRef"]


def reference_report():
    """{name: (ids, [Metadata files outside the music event XML and the preset's own file naming one of the ids])}."""
    files = []
    for d, _, names in os.walk(METADATA):
        files += [os.path.join(d, n) for n in names if n.endswith(".xml")]
    texts = {p: open(p, "r", encoding="utf-8").read() for p in files}
    out = {}
    for name in PARAMETERS:
        ids, own = [], None
        for p, t in texts.items():
            if os.path.basename(os.path.dirname(p)) != "ParameterPreset":
                continue
            m = re.search(r'<object class="ParameterPreset" id="(\{[0-9a-f-]+\})">\s*<property name="name">\s*<value>'
                          + re.escape(name) + r'</value>', t)
            if not m:
                continue
            own = p
            ids.append(m.group(1))
            g = re.search(r'<relationship name="parameter">\s*<destination>(\{[0-9a-f-]+\})', t)
            if g:
                ids.append(g.group(1))
        users = sorted(os.path.relpath(p, METADATA) for p, t in texts.items()
                       if p != own and os.path.basename(p) != EVENT_XML and any(i in t for i in ids))
        out[name] = (ids, users)
    return out


JS_TEMPLATE = r"""// Generated by FMOD/Tools/remove_music_event.py - edit the Python file, not this one.
// Deletes event:/Music/ChordPulseGame (only the Spike ref track may be left in it) and its now unused presets.
var KEEP_TRACK = "__KEEP_TRACK__";
var PARAMETERS = __PARAMETERS__;

function log(m) { console.log("[remove-music] " + m); }
var project = studio.project;
function valid(list) { return list.filter(function (x) { return x && x.isValid; }); }
function presetOf(name) {
    var p = project.lookup("parameter:/" + name);
    return p && p.isValid ? p : null;
}
function isParam(x, preset) { return x && (x.id === preset.id || (preset.parameter && x.id === preset.parameter.id)); }
var counts = { events: 0, presets: 0 };

var ev = project.lookup("__EVENT__");
if (ev) {   // lookup() returns it with isValid false; a missing event is null
    var total = 0, other = [];
    ev.groupTracks.forEach(function (t) {
        var n = t.modules.filter(function (m) { return m.entity === "SingleSound"; }).length;
        total += n;
        var name = t.mixerGroup ? t.mixerGroup.name : "(no group)";
        log("track " + name + ": " + n + " SingleSound");
        if (n && name !== KEEP_TRACK) other.push(name + " (" + n + ")");
    });
    var master = ev.masterTrack ? ev.masterTrack.modules.filter(function (m) { return m.entity === "SingleSound"; }).length : 0;
    if (master) other.push("master track (" + master + ")");
    log("SingleSound in the event: " + (total + master));
    if (other.length) {
        other.forEach(function (o) { log("note outside " + KEEP_TRACK + ": " + o); });
        throw "the event has notes outside " + KEEP_TRACK + ": nothing deleted, nothing saved";
    }
    project.deleteObject(ev);
    counts.events++;
    log("deleted __EVENT__");
} else log("__EVENT__ not in the project");

PARAMETERS.forEach(function (name) {
    var preset = presetOf(name);
    if (!preset) return;
    var users = [];
    valid(project.model.ParameterProxy.findInstances()).forEach(function (p) { if (isParam(p.preset, preset)) users.push("proxy"); });
    valid(project.model.ParameterCondition.findInstances()).forEach(function (c) { if (isParam(c.parameter, preset)) users.push("condition"); });
    valid(project.model.AutomationCurve.findInstances()).forEach(function (c) { if (isParam(c.parameter, preset)) users.push("automation"); });
    if (users.length) { log("kept preset " + name + ": still used (" + users.length + ": " + users.slice(0, 5).join(", ") + ")"); return; }
    project.deleteObject(preset);
    counts.presets++;
    log("deleted parameter:/" + name);
});

log("deleted: " + JSON.stringify(counts));
if (counts.events || counts.presets) { project.save(); log("saved"); } else log("nothing to do");
"""


def js_text():
    return (JS_TEMPLATE.replace("__KEEP_TRACK__", KEEP_TRACK)
            .replace("__PARAMETERS__", json.dumps(PARAMETERS))
            .replace("__EVENT__", EVENT))


def main():
    outside = False
    for name, (ids, users) in reference_report().items():
        if not ids:
            print(f"{name}: not in the project")
            continue
        print(f"{name} {' '.join(ids)}: used outside the music event by {users if users else 'nothing'}")
        outside = outside or bool(users)
    if outside:
        print("STOP: something outside the music event uses one of these; remove_music_event.js not written")
        sys.exit(1)
    changed = kill_oneshots.write_if_different(JS_PATH, js_text())
    print("remove_music_event.js", "written" if changed else "unchanged", "-", EVENT, "+", ", ".join(PARAMETERS))


if __name__ == "__main__":
    main()
