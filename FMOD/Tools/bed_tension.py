"""
Adaptive bed, axis 1: tension layers for event:/Music/ChordPulseGame (Docs/AdaptiveAudioPlan.md 8-1).

Writes bed_tension.js next to this file. Run it on the FMOD project (FMOD Studio closed) with
    fmodstudiocl.exe -script FMOD/Tools/bed_tension.js FMOD/ChordPulse/ChordPulse.fspro
It is idempotent: it removes what an earlier run made ("Tension *" tracks, its automation and filter).

Two game parameters, both 0..1 and smoothed by FMOD seek speed:
- Tension: how close the nearest enemy is / how low health is (Unity computes it).
    0.25-0.45  string pad fades in (one chord per bar)
    0.45-0.60  sub pulse on the off-beats fades in (between the kicks)
    0.65-0.85  the bass crossfades into a squelchy acid bass
- Danger: last life. A low-pass on "Music Bed" closes from 20 kHz to 900 Hz, so the accompaniment
  sounds smothered while kill chords and feature loops (outside Music Bed) stay clear.
Levels and curves were set from offline renders (bed RMS -36 dB): the layers add up to about
+1.5 dB at Tension 1, and the bass/acid crossfade does not dip.
All layers sit inside "Music Bed", so MusicMix still controls them.
Notes cover every bar of all four tempo sections; the chords are the usual C - Am - F - G per phrase.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

SECTIONS = []
_t = 0.0
for _bpm in (108, 116, 124, 132):
    SECTIONS.append((_t, _bpm))
    _t += 32 * 60.0 / _bpm
BARS_PER_SECTION = 8

# file, root (MIDI), peak short-term RMS (dB), attack onset seconds. AT / DeviceNTI roots match file names.
STRINGS = [("Synth/AT700_EnsembleStrings_A2_v90.wav", 45, -9.2, 0.072)]
SUB = [("SynthBass/DeviceNTI_SineSub_F1_v100.wav", 29, -9.2, 0.0),
       ("SynthBass/DeviceNTI_SineSub_C2_v100.wav", 36, -9.8, 0.0)]
ACID = [("SynthBass/AT303_Squelch_A1_v127.wav", 33, -16.8, 0.001),
        ("SynthBass/AT303_Squelch_C2_v127.wav", 36, -15.9, 0.001),
        ("SynthBass/AT303_Squelch_E2_v127.wav", 40, -15.7, 0.001),
        ("SynthBass/AT303_Squelch_A2_v127.wav", 45, -15.1, 0.001)]

# Per bar of the phrase: (pad voicing, bass root). Voicings stay in the low-mid register under the plucks.
CHORDS = [
    ((52, 55, 60), 36),   # C:  E3 G3 C4 / C2
    ((52, 57, 60), 33),   # Am: E3 A3 C4 / A1
    ((53, 57, 60), 29),   # F:  F3 A3 C4 / F1
    ((50, 55, 59), 31),   # G:  D3 G3 B3 / G1
]

# Note loudness at full layer volume (before the Tension automation). Set from offline renders
# against the accompaniment (bed RMS -36 dB at Intensity 1).
TARGET_DB = {"strings": -31.0, "sub": -27.0, "acid": -33.0}

# Track volume automation on Tension: (position, dB).
CURVES = {
    "strings": [(0.0, -80.0), (0.25, -80.0), (0.3, -20.0), (0.45, -6.0), (0.75, -2.0), (1.0, 0.0)],
    "sub": [(0.0, -80.0), (0.45, -80.0), (0.5, -15.0), (0.6, -4.0), (1.0, 0.0)],
    # Crossfade with the bass, kept roughly equal-power so the low end never dips in the middle.
    "acid": [(0.0, -80.0), (0.65, -80.0), (0.7, -12.0), (0.8, -3.0), (1.0, 0.0)],
    "bass": [(0.0, 0.0), (0.65, 0.0), (0.75, -3.0), (0.85, -15.0), (1.0, -80.0)],
}
DANGER_CUTOFF = [(0.0, 20000.0), (0.4, 5000.0), (1.0, 900.0)]

ACID_PATTERN = [0, 0, 12, 0, 0, 12, 0, 12]   # 8ths: root / octave bounce
SUB_BEATS = [0.5, 1.5, 2.5, 3.5]             # off-beats, between kicks and snares


def pick(table, midi):
    sample = min(table, key=lambda s: (abs(midi - s[1]), -s[1]))
    pitch = midi - sample[1]
    assert -24 <= pitch <= 24, (sample, midi)
    return sample, pitch


def note(track, table, midi, start, length, vol=0.0, shift=True):
    sample, pitch = pick(table, midi)
    ratio = 2 ** (pitch / 12.0)
    return {"track": track, "file": sample[0], "pitch": pitch,
            "start": round(start - (sample[3] / ratio if shift else 0.0), 6), "length": round(length, 6),
            "volume": round(max(-60.0, min(TARGET_DB[track] - sample[2] + vol, 10.0)), 2)}


def build():
    notes = []
    for start, bpm in SECTIONS:
        beat = 60.0 / bpm
        for bar in range(BARS_PER_SECTION):
            bar_start = start + bar * 4 * beat
            voicing, root = CHORDS[bar % 4]
            # A phrase downbeat may be a section-jump landing point: never start a note before it.
            first = bar % 4 == 0
            for m in voicing:
                notes.append(note("strings", STRINGS, m, bar_start, 4 * beat, shift=not first))
            for b in SUB_BEATS:
                notes.append(note("sub", SUB, root, bar_start + b * beat, 0.4 * beat))
            for i, offset in enumerate(ACID_PATTERN):
                notes.append(note("acid", ACID, root + offset, bar_start + i * 0.5 * beat, 0.4 * beat,
                                  vol=0.0 if i % 2 == 0 else -3.0))
    return notes


JS_TEMPLATE = r"""// Generated by FMOD/Tools/bed_tension.py - edit the Python file, not this one.
var NOTES = __NOTES__;
var CURVES = __CURVES__;
var DANGER_CUTOFF = __DANGER__;

function log(m) { console.log("[tension] " + m); }
var project = studio.project;
var ev = project.lookup("event:/Music/ChordPulseGame");
var assetsRoot = project.filePath.replace(/[^\/\\]+$/, "") + "Assets/";

function parameter(name, seekUp, seekDown) {
    var preset = project.lookup("parameter:/" + name);
    if (!preset) {
        project.workspace.addGameParameter({ name: name, type: project.parameterType.User, min: 0, max: 1 });
        preset = project.lookup("parameter:/" + name);
        log("created parameter " + name);
    }
    var p = preset.parameter;
    p.minimum = 0; p.maximum = 1; p.initialValue = 0;
    // Units per second: rise quickly when danger appears, relax slowly when it passes.
    p.seekSpeedAsymmetric = true; p.seekSpeed = seekUp; p.seekSpeedDescending = seekDown;
    var has = false;
    ev.parameters.forEach(function (x) { if (x.preset && (x.preset.id === p.id || x.preset.id === preset.id)) has = true; });
    if (!has) { ev.addGameParameter(preset); log("added " + name + " to event"); }
    return preset;
}
var tension = parameter("Tension", 2.0, 0.5);
var danger = parameter("Danger", 3.0, 1.0);

function groupByName(name) {
    var found = null;
    ev.groupTracks.forEach(function (t) { if (t.mixerGroup.name === name) found = t; });
    if (!found) throw "track not found: " + name;
    return found;
}
var musicBed = groupByName("Music Bed").mixerGroup;
var bass = groupByName("Bass - C Am F G").mixerGroup;

// --- undo an earlier run ---
var old = [];
ev.groupTracks.forEach(function (t) { if (/^Tension /.test(t.mixerGroup.name)) old.push(t); });
old.forEach(function (t) { project.deleteObject(t); });
function dropAutomation(owner, presetToDrop) {
    owner.automators.slice().forEach(function (a) {
        a.automationCurves.slice().forEach(function (c) {
            if (c.parameter && c.parameter.id === presetToDrop.parameter.id) project.deleteObject(c);
        });
        if (a.automationCurves.length === 0) project.deleteObject(a);
    });
}
dropAutomation(bass, tension);
// Only the low-pass this script made (automated by Danger); other scripts add their own Music Bed effects.
musicBed.effectChain.effects.slice().forEach(function (e) {
    if (e.entity !== "LowpassEffect") return;
    var ours = false;
    e.automators.forEach(function (a) {
        a.automationCurves.forEach(function (c) { if (c.parameter && c.parameter.id === danger.parameter.id) ours = true; });
    });
    if (ours) project.deleteObject(e);
});
if (old.length) log("removed " + old.length + " old tension tracks");

function automate(owner, property, preset, points) {
    var automator = null;
    owner.automators.forEach(function (a) { if (a.nameOfPropertyBeingAutomated === property) automator = a; });
    if (!automator) automator = owner.addAutomator(property);
    var curve = automator.addAutomationCurve(preset.parameter);
    points.forEach(function (pt) { curve.addAutomationPoint(pt[0], pt[1]); });
    return curve;
}

// --- Danger: smother the accompaniment ---
var lowpass = musicBed.effectChain.addEffect("LowpassEffect");
lowpass.cutoff = 20000; lowpass.resonance = 1;
automate(lowpass, "cutoff", danger, DANGER_CUTOFF);
// --- Tension: bass hands over to the acid bass ---
automate(bass, "volume", tension, CURVES.bass);

// --- audio files ---
var files = {};
function audioFile(rel) {
    if (files[rel]) return files[rel];
    var found = null;
    project.model.AudioFile.findInstances().forEach(function (a) {
        if (a.isValid && a.masterAssetFolder && a.length > 0 && a.assetPath === rel) found = a;
    });
    if (!found) { found = project.importAudioFile(assetsRoot + rel); log("imported " + rel); }
    if (!found) throw "could not import " + rel;
    files[rel] = found;
    return found;
}

function addTrack(name, output) {
    var t = project.create("GroupTrack");
    t.mixerGroup.name = name;
    t.mixerGroup.output = output;
    ev.relationships.groupTracks.add(t);
    return t;
}
var tracks = {
    strings: addTrack("Tension strings", musicBed),
    sub: addTrack("Tension sub", musicBed),
    acid: addTrack("Tension acid bass", musicBed),
};
var sHp = tracks.strings.mixerGroup.effectChain.addEffect("HighpassEffect");
sHp.cutoff = 140; sHp.resonance = 1;
var aLp = tracks.acid.mixerGroup.effectChain.addEffect("LowpassEffect");
aLp.cutoff = 3500; aLp.resonance = 1;
["strings", "sub", "acid"].forEach(function (k) { automate(tracks[k].mixerGroup, "volume", tension, CURVES[k]); });

var envelope = { strings: [250, 400], sub: [3, 60], acid: [2, 50] };   // attack / release ms
NOTES.forEach(function (n) {
    var s = tracks[n.track].addSound(ev.timeline, "SingleSound", n.start, n.length);
    s.audioFile = audioFile(n.file);
    s.pitch = n.pitch;
    s.volume = n.volume;
    var env = project.create("ADSRModulator");
    env.nameOfPropertyBeingModulated = "volume";
    env.attackTime = envelope[n.track][0]; env.releaseTime = envelope[n.track][1];
    env.objectBeingModulated = s;
});
log("placed " + NOTES.length + " notes");
project.save();
log("saved");
"""


def main():
    notes = build()
    curves = {k: v for k, v in CURVES.items()}
    js = (JS_TEMPLATE.replace("__NOTES__", json.dumps(notes)).replace("__CURVES__", json.dumps(curves))
          .replace("__DANGER__", json.dumps(DANGER_CUTOFF)))
    with open(os.path.join(HERE, "bed_tension.js"), "w", encoding="utf-8") as f:
        f.write(js)
    counts = {}
    for n in notes:
        counts[n["track"]] = counts.get(n["track"], 0) + 1
    print(counts, "->", "bed_tension.js")


if __name__ == "__main__":
    main()
