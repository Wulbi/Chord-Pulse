"""
Legacy gate: every note of the old timeline tracks that the pattern layers replace (patterns.LEGACY_TRACKS) only plays
while the global parameter LegacyLayers is 1. Unity sets LegacyLayers = 0 when the PatternScheduler plays those layers as
one-shots (SoundManager.legacyLayers false) and 1 to hear the old timeline path.

Writes legacy_gate.js next to this file. Run order (Docs/AdaptiveAudioPlan.md 8-10): ... bed_* -> instruments.js ->
mixer.js (creates LegacyLayers) -> kill_oneshots.js -> legacy_gate.js, FMOD Studio closed, then build as a SEPARATE
command (the CLI can crash after saving a big script; this one touches about 6,300 notes):
    python -I FMOD/Tools/legacy_gate.py
    fmodstudiocl.exe -script FMOD/Tools/legacy_gate.js FMOD/ChordPulse/ChordPulse.fspro
    fmodstudiocl.exe -script FMOD/Tools/legacy_gate.js FMOD/ChordPulse/ChordPulse.fspro   # check: all counters 0
    fmodstudiocl.exe -build FMOD/ChordPulse/ChordPulse.fspro
Any bed_* script that re-creates the migrated notes drops their gate: run legacy_gate.js again after it.

The gate is ADDED to each note's conditions (style / variation / combo / intensity stay); only the tracks in
LEGACY_TRACKS are touched (feature, fever, Spike ref and everything else are left alone). Idempotent: a note that
already has exactly GATE is unchanged; one with another LegacyLayers range gets it replaced. A second run logs
added 0, replaced 0 and does not save.

GATE range, measured (Task 11, on a copy of the project, FMOD Studio 2.02.35, bank rendered offline with WAVWRITER_NRT):
LegacyLayers is discrete (Studio maximum 2, runtime values 0 and 1), and a condition [lo, hi] on a discrete parameter
matches the values v with ceil(lo) <= v <= ceil(hi). At value 1 / value 0: [0.5, 1] plays / silent, [1, 1] plays /
silent, [0.6, 1.4] and [1, 2] and [0.5, 1.5] and [0.9, 1.1] play / silent, [1.1, 1.9] and [1.5, 2] silent / silent,
[0, 0.4] and [-0.4, 0.4] and [0, 1] play / play, [0, 0] silent / plays. So the brief's [0.5, 1] is exactly {1}.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import kill_oneshots  # noqa: E402  (write_if_different)
import patterns  # noqa: E402

JS_PATH = os.path.join(HERE, "legacy_gate.js")
PARAMETER = "LegacyLayers"
GATE = (0.5, 1.0)
# The 13 tracks of the Task 11 brief and the 10 drum tracks of Task 12 (the three core tracks included; Eighth-note hats
# holds both Core hat and Open hat); LEGACY_TRACKS (each migrated track once) must name exactly these.
EXPECTED_TRACKS = {
    "Bass - C Am F G", "Offbeat pluck", "Combo pad", "Combo bells", "Tension strings", "Tension sub",
    "Tension acid bass", "Latin marimba", "Funk keys", "Funk guitar", "Dreamy choir", "Dreamy bells", "Dreamy sub",
    "Kick - beats 1 and 3", "Snare - beats 2 and 4", "Eighth-note hats", "Clap layer", "Snare variations", "Combo hats",
    "Latin perc", "Latin shaker", "Funk drums", "Dreamy perc",
}


def tracks():
    names = patterns.LEGACY_TRACKS
    assert len(names) == len(set(names)) == len(EXPECTED_TRACKS) and set(names) == EXPECTED_TRACKS, names
    return names


JS_TEMPLATE = r"""// Generated by FMOD/Tools/legacy_gate.py - edit the Python file, not this one.
// Adds the LegacyLayers gate to every note of the migrated timeline tracks (idempotent).
var TRACKS = __TRACKS__;
var GATE = __GATE__;

function log(m) { console.log("[legacy-gate] " + m); }
var project = studio.project;
var ev = project.lookup("event:/Music/ChordPulseGame");
if (!ev) throw "event:/Music/ChordPulseGame not found";
var preset = project.lookup("parameter:/__PARAMETER__");
if (!preset) throw "parameter:/__PARAMETER__ not found (run mixer.js first)";

function gateOf(sound) {
    var found = [];
    sound.triggerConditions.forEach(function (c) { if (c.parameter && c.parameter.id === preset.parameter.id) found.push(c); });
    return found;
}

var counts = { notes: 0, added: 0, replaced: 0, unchanged: 0 };
var perTrack = [];
TRACKS.forEach(function (name) {
    var matches = [];
    ev.groupTracks.forEach(function (t) { if (t.mixerGroup.name === name) matches.push(t); });
    if (matches.length !== 1) throw "track " + name + ": " + matches.length + " tracks with that name";
    var n = 0;
    matches[0].modules.forEach(function (s) {
        if (s.entity !== "SingleSound") throw "track " + name + ": unexpected module " + s.entity;
        n++;
        var g = gateOf(s);
        if (g.length === 1 && Math.abs(g[0].minimum - GATE[0]) < 1e-6 && Math.abs(g[0].maximum - GATE[1]) < 1e-6) {
            counts.unchanged++;
            return;
        }
        g.forEach(function (c) { project.deleteObject(c); });
        s.addParameterCondition(preset, GATE[0], GATE[1]);
        if (g.length) counts.replaced++; else counts.added++;
    });
    counts.notes += n;
    perTrack.push(name + " " + n);
});
log("tracks: " + perTrack.join(", "));
log("notes " + counts.notes + ", added " + counts.added + ", replaced " + counts.replaced + ", unchanged " + counts.unchanged);
if (counts.added || counts.replaced) { project.save(); log("saved"); } else log("nothing to do");
"""


def js_text():
    return (JS_TEMPLATE.replace("__TRACKS__", json.dumps(tracks()))
            .replace("__GATE__", json.dumps(list(GATE)))
            .replace("__PARAMETER__", PARAMETER))


def main():
    changed = kill_oneshots.write_if_different(JS_PATH, js_text())
    print("legacy_gate.js", "written" if changed else "unchanged", "-", len(tracks()), "tracks, gate", PARAMETER, list(GATE))


if __name__ == "__main__":
    main()
