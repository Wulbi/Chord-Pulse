using System.Collections.Generic;
using System.Text;
using NUnit.Framework;

/// <summary>
/// Static check: every note the code can voice has a sample in the instrument library. A missing note is
/// silent at runtime, so it is pinned here. Later pattern tables add their notes through <see cref="AssertCovered"/>.
/// </summary>
public class InstrumentCoverageTests
{
    /// <summary>Fails listing every (instrument, bus, MIDI) that InstrumentTable has no sample for.</summary>
    public static void AssertCovered(IEnumerable<(Instrument, OutputBus, int)> notes)
    {
        var missing = new StringBuilder();
        foreach (var (instrument, bus, midi) in notes)
            if (!InstrumentTable.Has(instrument, bus, midi))
                missing.AppendLine($"no sample: instrument {instrument}, bus {bus}, MIDI {midi}");
        Assert.AreEqual(0, missing.Length, missing.ToString());
    }

    [Test]
    public void EveryVoicedKillNoteExists()
    {
        var failures = new StringBuilder();
        var list = new List<KillNote>();
        for (int style = 0; style < KillChordTable.Styles; style++)
            for (int color = 0; color < KillChordTable.Colors; color++)
                for (int chord = 0; chord < 4; chord++)
                    for (int voicing = 0; voicing <= 3; voicing++)
                        foreach (int combo in new[] { 0, 1, 2, 3 })
                            foreach (float tension in new[] { 0f, 0.7f })
                            {
                                list.Clear();
                                KillChordVoicer.Voice(style, color, chord, voicing, combo, tension, list);
                                foreach (var n in list)
                                    if (!InstrumentTable.Has(n.Instrument, OutputBus.KillChords, n.Midi))
                                        failures.AppendLine($"style {style} color {color} chord {chord} voicing {voicing} combo {combo} tension {tension}: instrument {n.Instrument} has no sample for MIDI {n.Midi}");
                            }
        Assert.AreEqual(0, failures.Length, failures.ToString());
    }

    [Test]
    public void EveryPatternNoteExists()
    {
        Assert.Greater(PatternTable.Notes.Length, 0, "the pattern table is empty");
        var notes = new List<(Instrument, OutputBus, int)>();
        bool drums = false, latinDrums = false;
        foreach (var n in PatternTable.Notes)
        {
            notes.Add((n.Instrument, n.Bus, n.Midi));
            drums |= n.Instrument == Instrument.Drums && n.Bus == OutputBus.MusicBed;
            latinDrums |= n.Instrument == Instrument.Drums && n.Bus == OutputBus.LatinPerc;
        }
        // Task 12: the drum kit (Note = percussion number) on the bed bus and on the Latin perc sub-bus is covered too.
        Assert.IsTrue(drums && latinDrums, "the pattern table has no drum notes on MusicBed / LatinPerc");
        AssertCovered(notes);
    }

    /// <summary>The visuals read BedNotes; it must list the same (beat, MIDI) as the pattern clips the scheduler plays.</summary>
    [TestCase("BassDrive")]
    [TestCase("BassWalk")]
    [TestCase("PluckArpeggio")]
    [TestCase("PluckStabs")]
    [TestCase("ComboBells")]
    public void BedNotesGenerated_MatchesPatternData(string clipName)
    {
        int index = System.Array.IndexOf(PatternTable.ClipNames, clipName);
        Assert.GreaterOrEqual(index, 0, $"no pattern clip {clipName}");
        var clip = PatternTable.Clips[index];
        var fromPattern = new SortedSet<(float, int)>();
        for (int i = clip.First; i < clip.First + clip.Count; i++)
            fromPattern.Add((PatternTable.Notes[i].Beat, PatternTable.Notes[i].Midi));
        var fromBedNotes = new SortedSet<(float, int)>();
        foreach (var n in BedNotesArray(clipName))
            fromBedNotes.Add((n.Beat, n.Midi));
        CollectionAssert.AreEqual(fromBedNotes, fromPattern);
    }

    /// <summary>
    /// The feature instrument (FeatureSelector flag) a feature-loop note plays as: each old Feature track is one sub-bus of
    /// bus:/Feature (FMOD/Tools/pattern_feature.py). 0 = not a feature bus.
    /// </summary>
    public static FeatureSelector.Instrument FeatureFlag(OutputBus bus)
    {
        switch (bus)
        {
            case OutputBus.Trumpet: return FeatureSelector.Instrument.Trumpet;
            case OutputBus.Whistle: return FeatureSelector.Instrument.Whistle;
            case OutputBus.Mallets: return FeatureSelector.Instrument.Mallets;
            case OutputBus.Perc: return FeatureSelector.Instrument.Percussion;
            case OutputBus.Synth: return FeatureSelector.Instrument.Synth;
            case OutputBus.Guitar: return FeatureSelector.Instrument.Guitar;
        }
        return 0;
    }

    /// <summary>
    /// FeatureSelector and the visuals read FeatureLoopNotes (generated by feature_loops.py from pattern_feature.py's loops);
    /// it must describe what the scheduler plays: per loop, every (beat, instrument) onset with its highest MIDI note
    /// (percussion 72) and voice count, the loop's instruments and bars, recomputed from the pattern clips of that loop.
    /// </summary>
    [Test]
    public void FeatureLoopNotes_MatchPatternData()
    {
        Assert.AreEqual(18, FeatureLoopNotes.Loops.Length); // 12 phrase loops + 6 fever guests (ids 13-18)
        for (int id = 1; id <= FeatureLoopNotes.Loops.Length; id++)
            Assert.AreEqual(id > 12, FeatureLoopNotes.Loops[id - 1].Fever, $"loop {id} fever flag");
        for (int id = 1; id <= FeatureLoopNotes.Loops.Length; id++)
        {
            var onsets = new SortedDictionary<(float beat, int flag), (int midi, int voices)>();
            FeatureSelector.Instrument flags = 0;
            float first = float.MaxValue, last = float.MinValue;
            for (int c = 0; c < PatternTable.Clips.Length; c++)
            {
                var clip = PatternTable.Clips[c];
                if (clip.FeatureLoop != id)
                    continue;
                for (int i = clip.First; i < clip.First + clip.Count; i++)
                {
                    var n = PatternTable.Notes[i];
                    var flag = FeatureFlag(n.Bus);
                    Assert.AreNotEqual((FeatureSelector.Instrument)0, flag, $"loop {id}: note on bus {n.Bus}, not a feature bus");
                    int midi = flag == FeatureSelector.Instrument.Percussion ? 72 : n.Midi;
                    var key = (n.Beat, (int)flag);
                    onsets[key] = onsets.TryGetValue(key, out var have) ? (System.Math.Max(have.midi, midi), have.voices + 1) : (midi, 1);
                    flags |= flag;
                    first = System.Math.Min(first, n.Beat);
                    last = System.Math.Max(last, n.Beat);
                }
            }
            var expected = new List<string>();
            foreach (var pair in onsets)
                expected.Add($"{pair.Key.beat} {pair.Value.midi} {pair.Value.voices} {pair.Key.flag}");
            var actual = new List<string>();
            foreach (var n in FeatureLoopNotes.ById[id])
                actual.Add($"{n.Beat} {n.Midi} {n.Voices} {(int)n.Instrument}");
            CollectionAssert.AreEqual(expected, actual, $"loop {id} onsets (beat, top MIDI, voices, instrument)");

            var loop = FeatureLoopNotes.Loops[id - 1];
            Assert.AreEqual(id, loop.Id);
            Assert.AreEqual(flags, loop.Instruments, $"loop {id} instruments");
            Assert.AreEqual(loop.StartBar, (int)(first / 4), $"loop {id}: first note {first} not in its first bar");
            Assert.AreEqual(loop.StartBar + loop.Bars - 1, (int)(last / 4), $"loop {id}: last note {last} not in its last bar");
        }
    }

    /// <summary>
    /// The eight fever tracks (FMOD/Tools/pattern_fever.py): one layer and, in the original fever (bed variant 0), one clip
    /// each, in the phase of its old condition (FeverBuild / FeverImpact / Fever = the whole fever phrase / FeverOutro),
    /// and every note voiced. Variants 1-3 add their own clips to the lead / shaker / bass layers.
    /// </summary>
    [TestCase("Fever lead", "FeverLead", FeverPhaseMask.Impact | FeverPhaseMask.Fever | FeverPhaseMask.Outro, 20)]
    [TestCase("Fever shaker", "FeverShaker", FeverPhaseMask.Impact | FeverPhaseMask.Fever | FeverPhaseMask.Outro, 32)]
    [TestCase("Fever bass fifths", "FeverBassFifths", FeverPhaseMask.Impact | FeverPhaseMask.Fever | FeverPhaseMask.Outro, 8)]
    [TestCase("Fever build roll", "FeverBuildRoll", FeverPhaseMask.Build, 48)]
    [TestCase("Fever build riser", "FeverBuildRiser", FeverPhaseMask.Build, 32)]
    [TestCase("Fever impact", "FeverImpact", FeverPhaseMask.Impact, 12)]
    [TestCase("Fever outro fall", "FeverOutroFall", FeverPhaseMask.Outro, 32)]
    [TestCase("Fever outro snare", "FeverOutroSnare", FeverPhaseMask.Outro, 32)]
    public void FeverClips_OnePerTrack_InTheirPhase(string layer, string clipName, FeverPhaseMask phases, int notes)
    {
        int layerIndex = System.Array.IndexOf(PatternTable.LayerNames, layer);
        Assert.GreaterOrEqual(layerIndex, 0, $"no layer {layer}");
        Assert.AreEqual(0UL, PatternTable.CoreLayerMask & (1UL << layerIndex), "fever layers are not core layers");
        int clips = 0;
        foreach (var c in PatternTable.Clips)
            if (c.Layer == layerIndex && (c.FeverVariantMask & 1) != 0)
                clips++;
        Assert.AreEqual(1, clips, $"variant-0 clips of {layer}");
        var clip = PatternTable.Clips[System.Array.IndexOf(PatternTable.ClipNames, clipName)];
        Assert.AreEqual(layerIndex, clip.Layer);
        Assert.AreEqual(phases, clip.Fever);
        Assert.AreEqual((15, 0, 4, 0, 0f, 0), (clip.StyleMask, (int)clip.VariationMin, (int)clip.VariationMax, (int)clip.ComboMin, clip.IntensityMin, (int)clip.FeatureLoop));
        Assert.AreEqual(notes, clip.Count);
        var voiced = new List<(Instrument, OutputBus, int)>();
        for (int i = clip.First; i < clip.First + clip.Count; i++)
            voiced.Add((PatternTable.Notes[i].Instrument, PatternTable.Notes[i].Bus, PatternTable.Notes[i].Midi));
        AssertCovered(voiced);
    }

    static BedNotes.Note[] BedNotesArray(string name)
    {
        switch (name)
        {
            case "BassDrive": return BedNotes.BassDrive;
            case "BassWalk": return BedNotes.BassWalk;
            case "PluckArpeggio": return BedNotes.PluckArpeggio;
            case "PluckStabs": return BedNotes.PluckStabs;
            case "ComboBells": return BedNotes.ComboBells;
        }
        throw new System.ArgumentException(name);
    }
}
